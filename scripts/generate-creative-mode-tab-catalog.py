#!/usr/bin/env python3
"""Generate the checked-in Vanilla 26.1 creative-mode tab catalog."""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root

from creative_mode_tab_catalog_extractor import (
    CreativeModeTabDefinition,
    CreativeModeTabEntry,
    extract_creative_mode_tab_catalog,
)
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT / "crates/bbb-world/src/creative_inventory/generated_26_1.rs"
)
SOURCES = {
    "tabs": Path("net/minecraft/world/item/CreativeModeTabs.java"),
    "tab": Path("net/minecraft/world/item/CreativeModeTab.java"),
    "items": Path("net/minecraft/world/item/Items.java"),
    "item_ids": Path("net/minecraft/references/ItemIds.java"),
}

VISIBILITY_VARIANTS = {
    "parent_and_search": "ParentAndSearch",
    "parent_only": "ParentOnly",
    "search_only": "SearchOnly",
}
DYNAMIC_VARIANTS = {
    "enchantment_books_all": "EnchantmentBooksAllLevels",
    "enchantment_books_max": "EnchantmentBooksMaxLevel",
    "fireworks": "FireworksAllDurations",
    "light_levels": "LightLevels",
    "ominous_banner": "OminousBanner",
    "ominous_bottles": "OminousBottles",
    "suspicious_stews": "SuspiciousStews",
    "test_block_modes": "TestBlockModes",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.source_root = resolve_source_root(args)
    return args


def _rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _entry_lines(entry: CreativeModeTabEntry) -> list[str]:
    visibility = VISIBILITY_VARIANTS[entry.visibility]
    if entry.kind == "item":
        if entry.item_resource_id is None:
            raise ValueError("static creative item lacks a resource id")
        return [
            "    CreativeInventoryCatalogEntry::Item {",
            f"        resource_id: {_rust_string(entry.item_resource_id)},",
            f"        visibility: CreativeInventoryTabVisibility::{visibility},",
            "    },",
        ]
    if entry.kind == "potions":
        if entry.item_resource_id is None:
            raise ValueError("creative potion family lacks an item resource id")
        dynamic = (
            "CreativeInventoryDynamicEntry::Potions { "
            f"item_resource_id: {_rust_string(entry.item_resource_id)} }}"
        )
    elif entry.kind == "instruments":
        if entry.item_resource_id is None or entry.tag_resource_id is None:
            raise ValueError("creative instrument family lacks item or tag identity")
        dynamic = (
            "CreativeInventoryDynamicEntry::Instruments { "
            f"item_resource_id: {_rust_string(entry.item_resource_id)}, "
            f"tag_resource_id: {_rust_string(entry.tag_resource_id)} }}"
        )
    elif entry.kind == "preset_paintings":
        if entry.painting_placeable is None:
            raise ValueError("creative painting family lacks its placeable predicate")
        dynamic = (
            "CreativeInventoryDynamicEntry::PresetPaintings { "
            f"placeable: {str(entry.painting_placeable).lower()} }}"
        )
    else:
        dynamic = (
            "CreativeInventoryDynamicEntry::"
            + DYNAMIC_VARIANTS[entry.kind]
        )
    return [
        "    CreativeInventoryCatalogEntry::Dynamic {",
        f"        kind: {dynamic},",
        f"        visibility: CreativeInventoryTabVisibility::{visibility},",
        "    },",
    ]


def _entries_name(tab: CreativeModeTabDefinition) -> str:
    return (
        tab.resource_id.split(":", 1)[1]
        .replace("/", "_")
        .upper()
        + "_ENTRIES"
    )


def render_catalog(tabs: tuple[CreativeModeTabDefinition, ...]) -> str:
    lines = [
        "// @generated by scripts/generate-creative-mode-tab-catalog.py; do not edit manually.",
        "// Sources: Vanilla 26.1 CreativeModeTabs.java, CreativeModeTab.java, Items.java, and ItemIds.java through the shared Tree-sitter Java frontend.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-creative-mode-tab-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-creative-mode-tab-catalog.py --check",
        "",
        "use super::{",
        "    CreativeInventoryBackground, CreativeInventoryCatalogEntry,",
        "    CreativeInventoryDynamicEntry, CreativeInventoryTab, CreativeInventoryTabRow,",
        "    CreativeInventoryTabType, CreativeInventoryTabVisibility,",
        "};",
        "",
    ]
    for tab in tabs:
        lines.append(
            f"const {_entries_name(tab)}: &[CreativeInventoryCatalogEntry] = &["
        )
        for entry in tab.entries:
            lines.extend(_entry_lines(entry))
        lines.extend(("];", ""))

    lines.append(
        "pub(super) const VANILLA_CREATIVE_INVENTORY_TABS: &[CreativeInventoryTab] = &["
    )
    for tab in tabs:
        background = "".join(part.title() for part in tab.background.split("_"))
        lines.extend(
            (
                "    CreativeInventoryTab {",
                f"        resource_id: {_rust_string(tab.resource_id)},",
                f"        row: CreativeInventoryTabRow::{tab.row.title()},",
                f"        column: {tab.column},",
                f"        title_key: {_rust_string(tab.title_key)},",
                f"        icon_item_resource_id: {_rust_string(tab.icon_item_resource_id)},",
                f"        tab_type: CreativeInventoryTabType::{tab.tab_type.title()},",
                f"        background: CreativeInventoryBackground::{background},",
                f"        aligned_right: {str(tab.aligned_right).lower()},",
                f"        show_title: {str(tab.show_title).lower()},",
                f"        can_scroll: {str(tab.can_scroll).lower()},",
                f"        requires_permissions: {str(tab.requires_permissions).lower()},",
                f"        entries: {_entries_name(tab)},",
                "    },",
            )
        )
    lines.extend(
        (
            "];",
            "",
            "#[cfg(test)]",
            "mod tests {",
            "    use std::{collections::HashSet, fs, path::Path};",
            "",
            "    use bbb_protocol::item_types::vanilla_item_type_for_resource_id;",
            "",
            "    use super::*;",
            "",
            "    #[test]",
            "    fn generated_creative_tabs_are_complete_ordered_and_resolvable() {",
            "        assert_eq!(VANILLA_CREATIVE_INVENTORY_TABS.len(), 14);",
            "        assert_eq!(",
            "            VANILLA_CREATIVE_INVENTORY_TABS",
            "                .iter()",
            "                .flat_map(|tab| tab.entries)",
            "                .filter(|entry| matches!(entry, CreativeInventoryCatalogEntry::Item { .. }))",
            "                .count(),",
            "            1674",
            "        );",
            "        assert_eq!(",
            "            VANILLA_CREATIVE_INVENTORY_TABS",
            "                .iter()",
            "                .flat_map(|tab| tab.entries)",
            "                .filter(|entry| matches!(entry, CreativeInventoryCatalogEntry::Dynamic { .. }))",
            "                .count(),",
            "            16",
            "        );",
            "        let mut dynamic_counts = [0_usize; 11];",
            "        let mut visibility_counts = [0_usize; 3];",
            "        for entry in VANILLA_CREATIVE_INVENTORY_TABS.iter().flat_map(|tab| tab.entries) {",
            "            let visibility = entry.visibility();",
            "            visibility_counts[match visibility {",
            "                CreativeInventoryTabVisibility::ParentAndSearch => 0,",
            "                CreativeInventoryTabVisibility::ParentOnly => 1,",
            "                CreativeInventoryTabVisibility::SearchOnly => 2,",
            "            }] += 1;",
            "            let CreativeInventoryCatalogEntry::Dynamic { kind, .. } = entry else { continue };",
            "            dynamic_counts[match kind {",
            "                CreativeInventoryDynamicEntry::FireworksAllDurations => 0,",
            "                CreativeInventoryDynamicEntry::Instruments { item_resource_id, .. } => {",
            "                    assert!(vanilla_item_type_for_resource_id(item_resource_id).is_some());",
            "                    1",
            "                }",
            "                CreativeInventoryDynamicEntry::Potions { item_resource_id } => {",
            "                    assert!(vanilla_item_type_for_resource_id(item_resource_id).is_some());",
            "                    2",
            "                }",
            "                CreativeInventoryDynamicEntry::SuspiciousStews => 3,",
            "                CreativeInventoryDynamicEntry::OminousBottles => 4,",
            "                CreativeInventoryDynamicEntry::EnchantmentBooksMaxLevel => 5,",
            "                CreativeInventoryDynamicEntry::EnchantmentBooksAllLevels => 6,",
            "                CreativeInventoryDynamicEntry::PresetPaintings { .. } => 7,",
            "                CreativeInventoryDynamicEntry::OminousBanner => 8,",
            "                CreativeInventoryDynamicEntry::TestBlockModes => 9,",
            "                CreativeInventoryDynamicEntry::LightLevels => 10,",
            "            }] += 1;",
            "        }",
            "        assert_eq!(dynamic_counts, [2, 1, 4, 1, 1, 1, 1, 2, 1, 1, 1]);",
            "        assert_eq!(visibility_counts, [1688, 1, 1]);",
            "        let expected_keys = [",
        )
    )
    lines.extend(
        f"            {_rust_string(tab.resource_id)}," for tab in tabs
    )
    lines.extend(
        (
            "        ];",
            "        assert_eq!(",
            "            VANILLA_CREATIVE_INVENTORY_TABS",
            "                .iter()",
            "                .map(|tab| tab.resource_id)",
            "                .collect::<Vec<_>>(),",
            "            expected_keys",
            "        );",
            "        for row in [CreativeInventoryTabRow::Top, CreativeInventoryTabRow::Bottom] {",
            "            assert_eq!(",
            "                VANILLA_CREATIVE_INVENTORY_TABS",
            "                    .iter()",
            "                    .filter(|tab| tab.row == row)",
            "                    .map(|tab| tab.column)",
            "                    .collect::<Vec<_>>(),",
            "                (0..=6).collect::<Vec<_>>()",
            "            );",
            "        }",
            "        let mut keys = HashSet::new();",
            "        for tab in VANILLA_CREATIVE_INVENTORY_TABS {",
            "            assert!(keys.insert(tab.resource_id));",
            "            assert!(vanilla_item_type_for_resource_id(tab.icon_item_resource_id).is_some());",
            "            let mut parent_items = HashSet::new();",
            "            for entry in tab.entries {",
            "                if let CreativeInventoryCatalogEntry::Item { resource_id, visibility } = entry {",
            "                    assert!(vanilla_item_type_for_resource_id(resource_id).is_some());",
            "                    if *visibility != CreativeInventoryTabVisibility::SearchOnly {",
            "                        assert!(parent_items.insert(resource_id));",
            "                    }",
            "                }",
            "            }",
            "        }",
            "        assert_eq!(",
            "            VANILLA_CREATIVE_INVENTORY_TABS",
            "                .iter()",
            "                .filter(|tab| tab.requires_permissions)",
            "                .map(|tab| tab.resource_id)",
            "                .collect::<Vec<_>>(),",
            "            vec![\"minecraft:op_blocks\"]",
            "        );",
            "    }",
            "",
            "    #[test]",
            "    fn production_sources_do_not_redeclare_creative_tab_catalog() {",
            "        fn visit(directory: &Path, violations: &mut Vec<String>) {",
            "            for entry in fs::read_dir(directory).unwrap() {",
            "                let path = entry.unwrap().path();",
            "                if path.is_dir() { visit(&path, violations); continue; }",
            "                if path.extension().and_then(|value| value.to_str()) != Some(\"rs\") { continue; }",
            "                let display = path.to_string_lossy();",
            "                if display.ends_with(\"/creative_inventory/generated_26_1.rs\") || display.ends_with(\"/tests.rs\") || display.contains(\"/tests/\") { continue; }",
            "                let source = fs::read_to_string(&path).unwrap();",
            "                let production = source.split(\"#[cfg(test)]\").next().unwrap_or(&source);",
            "                if production.contains(\"const VANILLA_CREATIVE_INVENTORY_TABS\")",
            "                    || production.contains(\"static VANILLA_CREATIVE_INVENTORY_TABS\")",
            "                { violations.push(display.into_owned()); }",
            "            }",
            "        }",
            "",
            "        let mut violations = Vec::new();",
            "        visit(Path::new(env!(\"CARGO_MANIFEST_DIR\")).parent().unwrap(), &mut violations);",
            "        assert!(violations.is_empty(), \"parallel creative tab catalogs: {violations:?}\");",
            "    }",
            "}",
            "",
        )
    )
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=False,
    )
    if formatted.returncode != 0:
        raise ValueError(
            f"rustfmt rejected generated creative tab catalog:\n{formatted.stderr}"
        )
    return formatted.stdout


def generate(source_root: Path) -> str:
    sources = {
        name: parse_source(
            relative_path.as_posix(), (source_root / relative_path).read_bytes()
        )
        for name, relative_path in SOURCES.items()
    }
    tabs = extract_creative_mode_tab_catalog(
        sources["tabs"],
        sources["tab"],
        sources["items"],
        sources["item_ids"],
    )
    return render_catalog(tabs)


def check_generated(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    generated = generate(args.source_root)
    if args.check:
        return 0 if check_generated(args.output, generated) else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
