#!/usr/bin/env python3
"""Generate the local_time ICU4J locale tables module from scripts/data TSVs.

The TSV inputs are dumped from the exact ICU4J 77.1 jar that vanilla 26.1
ships (scripts/local-time-icu4j/ has the dumper and its invocation); this
script only reshapes them into a deterministic Rust module so the client
carries no Java dependency. Regenerate with:

    python3 scripts/local_time_tables.py --write

`scripts/tests/test_local_time_tables.py` fails when the checked-in module
drifts from the TSVs.
"""

import argparse
import io
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "scripts" / "data"
OUTPUT = (
    ROOT
    / "crates"
    / "bbb-item-model"
    / "src"
    / "item_runtime"
    / "local_time"
    / "tables_26_1.rs"
)

QUARTER_FORMS = ["QQQ", "QQQQ", "QQQQQ", "qqq", "qqqq", "qqqqq"]


def read_rows(name):
    path = DATA / name
    return [
        line.split("\t")
        for line in path.read_text(encoding="utf-8").splitlines()
        if line
    ]


def rust_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    out = io.StringIO()
    out.write(
        "// Generated by scripts/local_time_tables.py from scripts/data/local-time-*.tsv\n"
        "// (ICU4J 77.1 dumps; the library vanilla 26.1 ships). Do not edit by hand.\n"
        "\n"
        "/// CLDR territory week data as ICU4J `Calendar.getWeekDataForRegion` reports\n"
        "/// it: `(region, first_day_of_week 1=Sunday..7=Saturday, minimal_days)`.\n"
        "#[rustfmt::skip]\n"
        "pub(super) const WEEK_DATA: &[(&str, u8, u8)] = &[\n"
    )
    for region, first, minimal in read_rows("local-time-week-data-26.1.tsv"):
        out.write(f"    ({rust_str(region)}, {first}, {minimal}),\n")
    out.write(
        "];\n"
        "\n"
        "/// Quarter names per locale id (row per `SimpleDateFormat` quarter form,\n"
        "/// four columns Q1..Q4). Locale ids are the vanilla language ids plus their\n"
        '/// bare languages and the root locale `""`.\n'
        "#[rustfmt::skip]\n"
        "pub(super) const QUARTERS: &[(&str, &str, [&str; 4])] = &[\n"
    )
    for row in read_rows("local-time-quarters-26.1.tsv"):
        locale, form, q1, q2, q3, q4 = row
        quarters = ", ".join(rust_str(q) for q in (q1, q2, q3, q4))
        out.write(f"    ({rust_str(locale)}, {rust_str(form)}, [{quarters}]),\n")
    out.write(
        "];\n"
        "\n"
        "/// `(locale, short, long)` localized-GMT rendering of a zero offset —\n"
        "/// ICU4J's `gmtZeroFormat`, which ICU4X does not apply.\n"
        "#[rustfmt::skip]\n"
        "pub(super) const GMT_ZERO: &[(&str, &str, &str)] = &[\n"
    )
    for locale, short, long in read_rows("local-time-gmt-zero-26.1.tsv"):
        out.write(f"    ({rust_str(locale)}, {rust_str(short)}, {rust_str(long)}),\n")
    out.write(
        "];\n"
        "\n"
        "/// Localized `VVV` exemplar-city fallback for zones without a city\n"
        "/// (ICU4J renders CLDR's `Etc/Unknown` city; ICU4X uses a different\n"
        "/// CLDR revision of that string).\n"
        "#[rustfmt::skip]\n"
        "pub(super) const UNKNOWN_CITY: &[(&str, &str)] = &[\n"
    )
    for locale, value in read_rows("local-time-unknown-city-26.1.tsv"):
        out.write(f"    ({rust_str(locale)}, {rust_str(value)}),\n")
    out.write(
        "];\n"
        "\n"
        "/// Root-locale generic/location zone names: ICU4J's root CLDR data\n"
        "/// renders territorial zones as their country code (`v`/`vvvv`/`VVVV`\n"
        "/// of Asia/Shanghai under the default `\\\"\\\"` locale is `CN`), which\n"
        "/// ICU4X's root data does not carry.\n"
        "#[rustfmt::skip]\n"
        "pub(super) const ROOT_ZONE_LOCATION: &[(&str, &str)] = &[\n"
    )
    for zone, value in read_rows("local-time-root-zone-location-26.1.tsv"):
        out.write(f"    ({rust_str(zone)}, {rust_str(value)}),\n")
    out.write(
        "];\n"
        "\n"
        "/// ICU4J flexible day periods (`B`), which ICU4X carries no data for:\n"
        "/// `(locale, minute_of_day the segment starts at, [abbreviated, wide,\n"
        "/// narrow])`, ordered by locale then minute. The segments are the observed\n"
        "/// output of `SimpleDateFormat` over every minute of a day, so they already\n"
        "/// include ICU4J's own rule application — `noon` spans 12:00-13:00 for `en`\n"
        "/// rather than being instantaneous.\n"
        "#[rustfmt::skip]\n"
        "pub(super) const DAY_PERIODS: &[(&str, u16, [&str; 3])] = &[\n"
    )
    for locale, minute, abbreviated, wide, narrow in read_rows(
        "local-time-day-periods-26.1.tsv"
    ):
        names = ", ".join(rust_str(name) for name in (abbreviated, wide, narrow))
        out.write(f"    ({rust_str(locale)}, {minute}, [{names}]),\n")
    out.write("];\n")
    return out.getvalue()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"wrote {OUTPUT}")
    elif args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            raise SystemExit(f"{OUTPUT} is stale; run scripts/local_time_tables.py --write")
        print("fresh")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
