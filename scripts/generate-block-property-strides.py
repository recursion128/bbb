#!/usr/bin/env python3
"""Generate mixed-radix block properties from the fixed global-state report."""

from __future__ import annotations

import argparse
import difflib
import json
import os
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "crates/bbb-facts/data/block_states_26_1.json"
OUTPUT = ROOT / "crates/bbb-facts/src/block_state_types/property_strides_26_1.rs"
BIN_OUTPUT = ROOT / "crates/bbb-facts/data/block_property_strides_26_1.bin"


def catalog(report):
    if report.get("version") != "26.1":
        raise ValueError("block-state report version must be 26.1")
    groups = {}
    for expected_id, state in enumerate(report["states"]):
        if state["id"] != expected_id:
            raise ValueError("block-state report must be contiguous")
        groups.setdefault(state["name"], []).append(state)
    blocks, properties, domains = [], [], []
    for name, states in groups.items():
        first = states[0]["id"]
        keys = sorted(states[0].get("properties", {}))
        if any(sorted(s.get("properties", {})) != keys for s in states):
            raise ValueError("block property keys differ")
        values = {k: tuple(dict.fromkeys(s["properties"][k] for s in states)) for k in keys}
        strides, product = {}, 1
        for key in reversed(keys):
            strides[key] = product
            product *= len(values[key])
        if product != len(states):
            raise ValueError("block states are not a complete cartesian product")
        for local, state in enumerate(states):
            if state["id"] != first + local or any(
                state["properties"][k] != values[k][local // strides[k] % len(values[k])]
                for k in keys
            ):
                raise ValueError("block states differ from mixed-radix ordering")
        blocks.append((name, first, len(properties), len(keys)))
        for key in keys:
            if values[key] not in domains:
                domains.append(values[key])
            properties.append((key, strides[key], domains.index(values[key])))
    return blocks, properties, domains


def _pack_tables(report):
    blocks, properties, domains = catalog(report)
    string_bytes = bytearray()
    string_spans: dict[str, tuple[int, int]] = {}

    def intern(text: str) -> tuple[int, int]:
        span = string_spans.get(text)
        if span is None:
            encoded = text.encode("utf-8")
            span = (len(string_bytes), len(encoded))
            string_bytes.extend(encoded)
            string_spans[text] = span
        return span

    domain_ranges: list[tuple[int, int]] = []
    domain_value_spans: list[tuple[int, int]] = []
    for domain in domains:
        start = len(domain_value_spans)
        for token in domain:
            domain_value_spans.append(intern(token))
        domain_ranges.append((start, len(domain)))

    block_rows = [
        (*intern(name), first, offset, count)
        for name, first, offset, count in blocks
    ]
    property_rows = [
        (*intern(name), stride, *domain_ranges[domain_idx])
        for name, stride, domain_idx in properties
    ]

    out = bytearray(string_bytes)
    domain_values_offset = len(out)
    for str_off, str_len in domain_value_spans:
        out.extend(struct.pack("<IH", str_off, str_len))
    blocks_offset = len(out)
    for name_off, name_len, first, offset, count in block_rows:
        out.extend(struct.pack("<IHiHH", name_off, name_len, first, offset, count))
    properties_offset = len(out)
    for name_off, name_len, stride, dom_start, dom_len in property_rows:
        out.extend(struct.pack("<IHiHH", name_off, name_len, stride, dom_start, dom_len))

    return (
        bytes(out),
        len(domain_value_spans),
        len(block_rows),
        len(property_rows),
        domain_values_offset,
        blocks_offset,
        properties_offset,
    )


def pack_binary(report) -> bytes:
    return _pack_tables(report)[0]


def render(report, bin_rel_path: str = "../../data/block_property_strides_26_1.bin") -> str:
    (
        _blob,
        domain_values_count,
        block_count,
        property_count,
        domain_values_offset,
        blocks_offset,
        properties_offset,
    ) = _pack_tables(report)
    lines = [
        "// @generated by scripts/generate-block-property-strides.py; do not edit.",
        "// StateDefinition property-name order and possible-value order from the 26.1 report.",
        "use super::{BlockProperties, PropertyStride};",
        "",
        f'const BYTES: &[u8] = include_bytes!("{bin_rel_path}");',
        f"const DOMAIN_VALUES_COUNT: usize = {domain_values_count};",
        f"const BLOCK_COUNT: usize = {block_count};",
        f"const PROPERTY_COUNT: usize = {property_count};",
        f"const DOMAIN_VALUES_OFFSET: usize = {domain_values_offset};",
        f"const BLOCKS_OFFSET: usize = {blocks_offset};",
        f"const PROPERTIES_OFFSET: usize = {properties_offset};",
        "",
        "#[inline]",
        "fn u16_at(offset: usize) -> u16 {",
        "    u16::from_le_bytes([BYTES[offset], BYTES[offset + 1]])",
        "}",
        "",
        "#[inline]",
        "fn u32_at(offset: usize) -> u32 {",
        "    u32::from_le_bytes([",
        "        BYTES[offset],",
        "        BYTES[offset + 1],",
        "        BYTES[offset + 2],",
        "        BYTES[offset + 3],",
        "    ])",
        "}",
        "",
        "#[inline]",
        "fn i32_at(offset: usize) -> i32 {",
        "    i32::from_le_bytes([",
        "        BYTES[offset],",
        "        BYTES[offset + 1],",
        "        BYTES[offset + 2],",
        "        BYTES[offset + 3],",
        "    ])",
        "}",
        "",
        "#[inline]",
        "fn str_at(offset: usize, len: usize) -> &'static str {",
        "    core::str::from_utf8(&BYTES[offset..offset + len])",
        '        .expect("valid UTF-8 in block_property_strides_26_1.bin")',
        "}",
        "",
        "pub(super) fn blocks() -> &'static [BlockProperties] {",
        "    static BLOCKS: std::sync::OnceLock<Box<[BlockProperties]>> = std::sync::OnceLock::new();",
        "    BLOCKS.get_or_init(|| {",
        "        (0..BLOCK_COUNT)",
        "            .map(|idx| {",
        "                let base = BLOCKS_OFFSET + idx * 14;",
        "                BlockProperties {",
        "                    name: str_at(u32_at(base) as usize, u16_at(base + 4) as usize),",
        "                    first: i32_at(base + 6),",
        "                    offset: u16_at(base + 10) as usize,",
        "                    count: u16_at(base + 12) as usize,",
        "                }",
        "            })",
        "            .collect::<Vec<_>>()",
        "            .into_boxed_slice()",
        "    })",
        "}",
        "",
        "pub(super) fn properties() -> &'static [PropertyStride] {",
        "    static DOMAIN_VALUES: std::sync::OnceLock<Box<[&'static str]>> = std::sync::OnceLock::new();",
        "    static PROPERTIES: std::sync::OnceLock<Box<[PropertyStride]>> = std::sync::OnceLock::new();",
        "    PROPERTIES.get_or_init(|| {",
        "        let domain_pool: &'static [&'static str] = DOMAIN_VALUES.get_or_init(|| {",
        "            (0..DOMAIN_VALUES_COUNT)",
        "                .map(|idx| {",
        "                    let base = DOMAIN_VALUES_OFFSET + idx * 6;",
        "                    str_at(u32_at(base) as usize, u16_at(base + 4) as usize)",
        "                })",
        "                .collect::<Vec<_>>()",
        "                .into_boxed_slice()",
        "        });",
        "        (0..PROPERTY_COUNT)",
        "            .map(|idx| {",
        "                let base = PROPERTIES_OFFSET + idx * 14;",
        "                let start = u16_at(base + 10) as usize;",
        "                let len = u16_at(base + 12) as usize;",
        "                PropertyStride {",
        "                    name: str_at(u32_at(base) as usize, u16_at(base + 4) as usize),",
        "                    stride: i32_at(base + 6),",
        "                    values: &domain_pool[start..start + len],",
        "                }",
        "            })",
        "            .collect::<Vec<_>>()",
        "            .into_boxed_slice()",
        "    })",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--bin-output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bin_output = args.bin_output
    if bin_output is None:
        bin_output = BIN_OUTPUT if args.output == OUTPUT else args.output.with_suffix(".bin")
    bin_rel = os.path.relpath(bin_output, args.output.parent).replace("\\", "/")
    report = json.loads(REPORT.read_text())
    output = render(report, bin_rel)
    blob = pack_binary(report)
    if args.check:
        actual = args.output.read_text() if args.output.exists() else ""
        actual_bin = bin_output.read_bytes() if bin_output.exists() else b""
        ok = True
        if actual != output:
            print(
                "".join(difflib.unified_diff(actual.splitlines(True), output.splitlines(True))),
                end="",
            )
            ok = False
        if actual_bin != blob:
            sys.stderr.write(
                f"binary output differs at {bin_output} "
                f"(actual {len(actual_bin)} B vs expected {len(blob)} B)\n"
            )
            ok = False
        return 0 if ok else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    bin_output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output)
    bin_output.write_bytes(blob)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
