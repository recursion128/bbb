"""Behavioral contract for the source-file size ratchet."""

from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

import source_file_size_ratchet as ratchet

REPO_ROOT = Path(__file__).resolve().parents[2]


def _write(path: Path, lines: int, *, generated: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = ["// @generated by a test; do not edit manually."] if generated else []
    body += [f"// line {index}" for index in range(lines - len(body))]
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


class SourceFileSizeRatchetTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.data_path = self.root / ratchet.DATA_PATH
        self.data_path.parent.mkdir(parents=True)
        self.crate = Path("crates/fake/src")
        _write(self.root / self.crate / "small.rs", 10)
        _write(self.root / self.crate / "big.rs", 40)
        _write(self.root / self.crate / "gen.rs", 500, generated=True)
        self._save({"big.rs": 45})

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def _save(self, pins: dict[str, int]) -> None:
        data = {
            "schema_version": 1,
            "line_cap": 20,
            "roots": ["crates/fake"],
            "pinned": {(self.crate / name).as_posix(): bound for name, bound in pins.items()},
        }
        self.data_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

    def _load_pins(self) -> dict[str, int]:
        return json.loads(self.data_path.read_text(encoding="utf-8"))["pinned"]

    def test_scan_skips_generated_files_and_counts_the_rest(self) -> None:
        counts = ratchet.scan(self.root, ratchet.load_data(self.root))
        self.assertEqual(
            counts,
            {(self.crate / "small.rs").as_posix(): 10, (self.crate / "big.rs").as_posix(): 40},
        )

    def test_check_passes_when_every_file_is_within_its_bound(self) -> None:
        self.assertEqual(ratchet.main(["check", "--repo-root", str(self.root)]), 0)

    def test_check_fails_for_a_new_file_over_the_cap(self) -> None:
        _write(self.root / self.crate / "new.rs", 21)
        self.assertEqual(ratchet.main(["check", "--repo-root", str(self.root)]), 1)

    def test_check_fails_when_a_pinned_file_grows_past_its_pin(self) -> None:
        _write(self.root / self.crate / "big.rs", 46)
        self.assertEqual(ratchet.main(["check", "--repo-root", str(self.root)]), 1)

    def test_check_fails_on_a_stale_pin_until_update_drops_it(self) -> None:
        _write(self.root / self.crate / "big.rs", 15)
        self.assertEqual(ratchet.main(["check", "--repo-root", str(self.root)]), 1)
        self.assertEqual(ratchet.main(["update", "--repo-root", str(self.root)]), 0)
        self.assertEqual(self._load_pins(), {})
        self.assertEqual(ratchet.main(["check", "--repo-root", str(self.root)]), 0)

    def test_update_lowers_pins_and_never_raises_or_adds_them(self) -> None:
        _write(self.root / self.crate / "big.rs", 30)
        _write(self.root / self.crate / "new.rs", 25)
        self.assertEqual(ratchet.main(["update", "--repo-root", str(self.root)]), 0)
        self.assertEqual(self._load_pins(), {(self.crate / "big.rs").as_posix(): 30})
        # The unpinned offender is still an offender: update is not an amnesty.
        self.assertEqual(ratchet.main(["check", "--repo-root", str(self.root)]), 1)
        _write(self.root / self.crate / "big.rs", 35)
        self.assertEqual(ratchet.main(["update", "--repo-root", str(self.root)]), 0)
        self.assertEqual(self._load_pins(), {(self.crate / "big.rs").as_posix(): 30})

    def test_repository_data_is_current(self) -> None:
        data = ratchet.load_data(REPO_ROOT)
        self.assertEqual(data["schema_version"], ratchet.SCHEMA_VERSION)
        self.assertEqual(data["line_cap"], 3000)
        counts = ratchet.scan(REPO_ROOT, data)
        self.assertEqual(ratchet.offenders(data, counts), [])
        self.assertEqual(ratchet.stale_pins(data, counts), [])
        for path in data["pinned"]:
            self.assertTrue((REPO_ROOT / path).is_file(), path)


if __name__ == "__main__":
    unittest.main()
