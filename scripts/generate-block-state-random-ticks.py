#!/usr/bin/env python3
"""Generate Vanilla 26.1 random-tick facts for every built-in block state."""

from __future__ import annotations

import argparse
import difflib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_runtime, resolve_runtime_inputs

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT / "crates/bbb-facts/src/block_state_types/random_tick_facts_26_1.rs"
)
BLOCK_STATES = REPO_ROOT / "crates/bbb-facts/data/block_states_26_1.json"
PROBE_SOURCE = REPO_ROOT / "scripts/vanilla-runtime/BlockStateRandomTickReport.java"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_runtime(parser)
    parser.add_argument("--facts-input", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    resolve_runtime_inputs(args)
    return args


def expected_state_count() -> int:
    report = json.loads(BLOCK_STATES.read_text())
    if report.get("version") != "26.1":
        raise ValueError("embedded block-state report is not for Vanilla 26.1")
    states = report.get("states")
    if not isinstance(states, list):
        raise ValueError("embedded block-state report lacks states")
    for expected_id, state in enumerate(states):
        if state.get("id") != expected_id:
            raise ValueError("embedded block-state report is not contiguous")
    return len(states)


def runtime_facts(args: argparse.Namespace) -> str:
    jars = [args.client_jar, *sorted(args.libraries_root.rglob("*.jar"))]
    missing = [path for path in (args.javac, args.java, *jars[:1]) if not path.is_file()]
    if missing:
        raise FileNotFoundError(
            "missing Vanilla runtime probe input: "
            + ", ".join(str(path) for path in missing)
        )
    classpath = os.pathsep.join(str(path) for path in jars)
    with tempfile.TemporaryDirectory(prefix="bbb-block-state-random-tick-") as directory:
        classes = Path(directory)
        subprocess.run(
            [
                str(args.javac),
                "-cp",
                classpath,
                "-d",
                str(classes),
                str(PROBE_SOURCE),
            ],
            check=True,
        )
        result = subprocess.run(
            [
                str(args.java),
                "-cp",
                os.pathsep.join((str(classes), classpath)),
                "BlockStateRandomTickReport",
            ],
            check=False,
            text=True,
            capture_output=True,
        )
        if result.returncode != 0:
            raise RuntimeError(
                "Vanilla block-state random-tick probe failed:\n" + result.stderr.strip()
            )
    return result.stdout


def _coalesce(ids: list[int]) -> tuple[tuple[int, int], ...]:
    ranges: list[list[int]] = []
    for state_id in ids:
        if not ranges or state_id != ranges[-1][1] + 1:
            ranges.append([state_id, state_id])
        else:
            ranges[-1][1] = state_id
    return tuple((start, end) for start, end in ranges)


def parse_facts(
    source: str, expected_count: int
) -> tuple[tuple[tuple[int, int], ...], tuple[tuple[int, int], ...]]:
    lines = source.splitlines()
    expected_header = f"version=26.1 count={expected_count}"
    if not lines or lines[0] != expected_header:
        raise ValueError(
            f"expected runtime report header {expected_header!r}, got "
            f"{lines[0] if lines else '<empty>'!r}"
        )
    if len(lines) != expected_count + 1:
        raise ValueError(
            f"expected {expected_count} runtime facts, got {len(lines) - 1}"
        )
    block_ids: list[int] = []
    fluid_ids: list[int] = []
    for expected_id, line in enumerate(lines[1:]):
        fields = line.split("\t")
        if (
            len(fields) != 3
            or fields[0] != str(expected_id)
            or fields[1] not in ("0", "1")
            or fields[2] not in ("0", "1")
        ):
            raise ValueError(f"invalid runtime fact at id {expected_id}: {line!r}")
        if fields[1] == "1":
            block_ids.append(expected_id)
        if fields[2] == "1":
            fluid_ids.append(expected_id)
    return _coalesce(block_ids), _coalesce(fluid_ids)


def render_rust(
    block_ranges: tuple[tuple[int, int], ...],
    fluid_ranges: tuple[tuple[int, int], ...],
) -> str:
    lines = [
        "// @generated by scripts/generate-block-state-random-ticks.py; do not edit manually.",
        "// Source: Vanilla 26.1 BlockState.isRandomlyTicking() and",
        "// BlockState.getFluidState().isRandomlyTicking(), evaluated by the checked-in",
        "// runtime probe. These are the two predicates LevelChunkSection.setBlockState",
        "// folds into tickingBlockCount / tickingFluidCount (LevelChunkSection.java:74-100).",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-block-state-random-ticks.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-block-state-random-ticks.py --check",
        "",
        # One-entry tables would otherwise be collapsed onto a single line by
        # rustfmt, which makes `--check` fail against a formatted tree.
        "#[rustfmt::skip]",
        "pub(super) const VANILLA_BLOCK_STATE_RANDOMLY_TICKING_RANGES: &[(i32, i32)] = &[",
    ]
    lines.extend(f"    ({start}, {end})," for start, end in block_ranges)
    lines.extend(
        (
            "];",
            "",
            "#[rustfmt::skip]",
            "pub(super) const VANILLA_BLOCK_STATE_FLUID_RANDOMLY_TICKING_RANGES: &[(i32, i32)] = &[",
        )
    )
    lines.extend(f"    ({start}, {end})," for start, end in fluid_ranges)
    lines.extend(("];", ""))
    return "\n".join(lines)


def check_output(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    count = expected_state_count()
    facts = (
        args.facts_input.read_text()
        if args.facts_input is not None
        else runtime_facts(args)
    )
    generated = render_rust(*parse_facts(facts, count))
    if args.check:
        return 0 if check_output(args.output, generated) else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
