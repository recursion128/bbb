#!/usr/bin/env python3
"""Generate/check Vanilla 26.1 entity default-attribute facts."""

from __future__ import annotations

import argparse
import difflib
import re
import struct
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root
from entity_metadata_extractor import EntityTypeRegistration, extract

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/bbb-facts/src/default_attributes_26_1.rs"
)
ATTRIBUTE_CATALOG = REPO_ROOT / "crates/bbb-facts/src/attribute_types.rs"
ATTRIBUTE_ID_PATTERN = re.compile(
    r"^pub const VANILLA_ATTRIBUTE_([A-Z0-9_]+)_ID: i32 = ([0-9]+);$",
    re.MULTILINE,
)
CANONICAL_RESOURCE_ID_PATTERN = re.compile(
    r"minecraft:[a-z0-9_.-]+(?:/[a-z0-9_.-]+)*\Z"
)


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    args.source_root = resolve_source_root(args)
    return args


def render_double(bits: int) -> str:
    """The Rust literal for an IEEE-754 double the extractor captured as bits.

    `repr` round-trips a Python float exactly, and Rust parses the same decimal
    to the same double, so the generated literal is the Java literal's value and
    not a re-rounded approximation of it.
    """
    value = struct.unpack("!d", struct.pack("!Q", bits))[0]
    text = repr(value)
    return text if any(character in text for character in ".eE") else f"{text}.0"


def attribute_ids(path: Path = ATTRIBUTE_CATALOG) -> dict[str, int]:
    source = path.read_text(encoding="utf-8")
    entries = {
        constant_name: int(attribute_id)
        for constant_name, attribute_id in ATTRIBUTE_ID_PATTERN.findall(source)
    }
    if len(entries) != 35 or set(entries.values()) != set(range(35)):
        raise ValueError(
            f"expected 35 contiguous attribute ids in {path}, found {len(entries)}"
        )
    return entries


def validate_rows(
    rows: Sequence[EntityTypeRegistration], ids: dict[str, int]
) -> None:
    if len(rows) != 157:
        raise ValueError(f"expected 157 Vanilla entity rows, found {len(rows)}")
    resources = [row.resource_id for row in rows]
    if len(resources) != len(set(resources)):
        raise ValueError("Vanilla entity resource ids are not unique")
    invalid_resources = [
        resource_id
        for resource_id in resources
        if CANONICAL_RESOURCE_ID_PATTERN.fullmatch(resource_id) is None
    ]
    if invalid_resources:
        raise ValueError(
            "non-canonical Vanilla entity resource ids: " + ", ".join(invalid_resources)
        )
    empty_attribute_rows = sum(not row.attribute_base_overrides for row in rows)
    if empty_attribute_rows != 65:
        raise ValueError(
            "expected 65 non-living/no-supplier entity rows, found "
            f"{empty_attribute_rows}"
        )
    for row in rows:
        constants = [constant for constant, _ in row.attribute_base_overrides]
        if len(constants) != len(set(constants)):
            raise ValueError(f"{row.resource_id}: duplicate default attributes")
        missing = sorted(set(constants) - ids.keys())
        if missing:
            raise ValueError(
                f"{row.resource_id}: attributes absent from protocol catalog: "
                + ", ".join(missing)
            )


def render_rows(rows: Sequence[EntityTypeRegistration], ids: dict[str, int]) -> str:
    validate_rows(rows, ids)
    used_constants = sorted(
        {
            constant
            for row in rows
            for constant, _ in row.attribute_base_overrides
        },
        key=ids.__getitem__,
    )
    lines = [
        "// @generated by scripts/generate-entity-default-attributes.py; do not edit manually.",
        "// Sources: Vanilla 26.1 DefaultAttributes and entity attribute factories.",
        "// Attribute ids and registry default values: bbb-facts attribute_types.rs.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-entity-default-attributes.py",
        "// Check: scripts/vanilla-source-tools.sh "
        "scripts/generate-entity-default-attributes.py --check",
        "",
        "use crate::attribute_types::{",
    ]
    lines.extend(
        f"    VANILLA_ATTRIBUTE_{constant}_ID," for constant in used_constants
    )
    lines.extend(
        [
            "};",
            "",
            "/// One entry of an entity type's `AttributeSupplier`: the attribute and the",
            "/// base value its factory declared. `None` is a bare",
            "/// `AttributeSupplier.Builder.add(Attribute)`, which takes the attribute's own",
            "/// registry default rather than declaring a base of its own.",
            "pub type VanillaEntityDefaultAttribute = (i32, Option<f64>);",
            "",
            "#[rustfmt::skip]",
            "const VANILLA_ENTITY_DEFAULT_ATTRIBUTES_26_1: &[",
            "    (&str, &[VanillaEntityDefaultAttribute])",
            "] = &[",
        ]
    )
    for row in rows:
        lines.append(f'    ("{row.resource_id}", &[')
        for constant, override_bits in row.attribute_base_overrides:
            base = (
                "None"
                if override_bits is None
                else f"Some({render_double(override_bits)})"
            )
            lines.append(f"        (VANILLA_ATTRIBUTE_{constant}_ID, {base}),")
        lines.append("    ]),")
    lines.extend(
        [
            "];",
            "",
            "pub fn vanilla_entity_default_attributes_26_1(",
            "    resource_id: &str,",
            ") -> Option<&'static [VanillaEntityDefaultAttribute]> {",
            "    VANILLA_ENTITY_DEFAULT_ATTRIBUTES_26_1",
            "        .iter()",
            "        .find(|(candidate, _)| *candidate == resource_id)",
            "        .map(|(_, attributes)| *attributes)",
            "}",
            "",
            "pub fn vanilla_entity_default_attributes_by_type_id_26_1(",
            "    entity_type_id: i32,",
            ") -> Option<&'static [VanillaEntityDefaultAttribute]> {",
            "    usize::try_from(entity_type_id)",
            "        .ok()",
            "        .and_then(|id| VANILLA_ENTITY_DEFAULT_ATTRIBUTES_26_1.get(id))",
            "        .map(|(_, attributes)| *attributes)",
            "}",
            "",
            "#[cfg(test)]",
            "mod tests {",
            "    use std::collections::HashSet;",
            "",
            "    use super::*;",
            "",
            "    #[test]",
            "    fn entity_default_attributes_26_1_rows_are_complete_and_unique() {",
            "        assert_eq!(VANILLA_ENTITY_DEFAULT_ATTRIBUTES_26_1.len(), 157);",
            "        let mut resource_ids = HashSet::new();",
            "        for (resource_id, attributes) in VANILLA_ENTITY_DEFAULT_ATTRIBUTES_26_1 {",
            '            assert!(resource_ids.insert(*resource_id), "duplicate {resource_id}");',
            '            assert!(resource_id.starts_with("minecraft:"));',
            "            let mut attribute_ids = HashSet::new();",
            "            for (attribute_id, base) in *attributes {",
            "                assert!(attribute_ids.insert(*attribute_id));",
            "                assert!(base.is_none_or(f64::is_finite));",
            "            }",
            "        }",
            "    }",
            "",
            "    #[test]",
            "    fn entity_default_attributes_26_1_lookup_distinguishes_non_living_and_unknown() {",
            "        assert_eq!(",
            '            vanilla_entity_default_attributes_26_1("minecraft:arrow"),',
            "            Some(&[][..])",
            "        );",
            "        assert!(",
            '            vanilla_entity_default_attributes_26_1("minecraft:not_real").is_none()',
            "        );",
            '        assert!(vanilla_entity_default_attributes_26_1("blaze").is_none());',
            "        for resource_id in [",
            '            "minecraft:blaze",',
            '            "minecraft:bogged",',
            '            "minecraft:breeze",',
            '            "minecraft:cave_spider",',
            '            "minecraft:elder_guardian",',
            '            "minecraft:giant",',
            '            "minecraft:guardian",',
            '            "minecraft:parched",',
            '            "minecraft:silverfish",',
            '            "minecraft:skeleton",',
            '            "minecraft:spider",',
            '            "minecraft:stray",',
            '            "minecraft:wither_skeleton",',
            "        ] {",
            "            assert!(!vanilla_entity_default_attributes_26_1(resource_id)",
            "                .unwrap()",
            "                .is_empty());",
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=False,
    )
    if formatted.returncode != 0:
        raise ValueError("rustfmt rejected generated source:\n" + formatted.stderr)
    return formatted.stdout


def render(source_root: Path, catalog: Path = ATTRIBUTE_CATALOG) -> str:
    return render_rows(extract(source_root).entity_types, attribute_ids(catalog))


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    generated = render(args.source_root)
    current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
    if args.check:
        if current == generated:
            return 0
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile=str(args.output) + " (generated)",
            )
        )
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
