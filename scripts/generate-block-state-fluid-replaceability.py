#!/usr/bin/env python3
"""Generate Vanilla 26.1 BlockState.canBeReplaced(Fluid) facts."""

from __future__ import annotations

import argparse
import difflib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_runtime, resolve_runtime_inputs


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/bbb-protocol/src/block_state_types/fluid_replaceability_26_1.rs"
)
BLOCK_STATES = REPO_ROOT / "crates/bbb-protocol/data/block_states_26_1.json"
PROBE_SOURCE = (
    REPO_ROOT
    / "scripts/vanilla-runtime/BlockStateFluidReplaceabilityReport.java"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_runtime(parser)
    parser.add_argument("--facts-input", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    resolve_runtime_inputs(args)
    return args


def expected_state_count() -> int:
    report = json.loads(BLOCK_STATES.read_text())
    if report.get("version") != "26.1":
        raise ValueError("embedded block-state report is not for Vanilla 26.1")
    states = report.get("states")
    if not isinstance(states, list):
        raise ValueError("embedded block-state report lacks states")
    for expected_id, state in enumerate(states):
        if state.get("id") != expected_id:
            raise ValueError("embedded block-state report is not contiguous")
    return len(states)


def runtime_facts(args: argparse.Namespace) -> str:
    jars = [args.client_jar, *sorted(args.libraries_root.rglob("*.jar"))]
    missing = [path for path in (args.javac, args.java, *jars[:1]) if not path.is_file()]
    if missing:
        raise FileNotFoundError(
            "missing Vanilla runtime probe input: "
            + ", ".join(str(path) for path in missing)
        )
    classpath = os.pathsep.join(str(path) for path in jars)
    with tempfile.TemporaryDirectory(prefix="bbb-block-state-fluid-") as directory:
        classes = Path(directory)
        subprocess.run(
            [
                str(args.javac),
                "-cp",
                classpath,
                "-d",
                str(classes),
                str(PROBE_SOURCE),
            ],
            check=True,
        )
        result = subprocess.run(
            [
                str(args.java),
                "-cp",
                os.pathsep.join((str(classes), classpath)),
                "BlockStateFluidReplaceabilityReport",
            ],
            check=False,
            text=True,
            capture_output=True,
        )
        if result.returncode != 0:
            raise RuntimeError(
                "Vanilla block-state fluid probe failed:\n" + result.stderr.strip()
            )
    return result.stdout


def parse_facts(source: str, expected_count: int) -> tuple[tuple[int, int], ...]:
    lines = source.splitlines()
    expected_header = f"version=26.1 count={expected_count}"
    if not lines or lines[0] != expected_header:
        raise ValueError(
            f"expected runtime report header {expected_header!r}, got "
            f"{lines[0] if lines else '<empty>'!r}"
        )
    if len(lines) != expected_count + 1:
        raise ValueError(
            f"expected {expected_count} runtime facts, got {len(lines) - 1}"
        )
    replaceable_ids = []
    for expected_id, line in enumerate(lines[1:]):
        fields = line.split("\t")
        if fields != [str(expected_id), "0"] and fields != [str(expected_id), "1"]:
            raise ValueError(f"invalid runtime fact at id {expected_id}: {line!r}")
        if fields[1] == "1":
            replaceable_ids.append(expected_id)
    ranges = []
    for state_id in replaceable_ids:
        if not ranges or state_id != ranges[-1][1] + 1:
            ranges.append([state_id, state_id])
        else:
            ranges[-1][1] = state_id
    return tuple((start, end) for start, end in ranges)


def render_rust(ranges: tuple[tuple[int, int], ...]) -> str:
    lines = [
        "// @generated by scripts/generate-block-state-fluid-replaceability.py; do not edit manually.",
        "// Source: Vanilla 26.1 BlockState.canBeReplaced(Fluid), evaluated by the checked-in runtime probe.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-block-state-fluid-replaceability.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-block-state-fluid-replaceability.py --check",
        "",
        "pub(super) const VANILLA_BLOCK_STATE_FLUID_REPLACEABLE_RANGES: &[(i32, i32)] = &[",
    ]
    lines.extend(f"    ({start}, {end})," for start, end in ranges)
    lines.extend(("];", ""))
    return "\n".join(lines)


def check_output(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    count = expected_state_count()
    facts = (
        args.facts_input.read_text()
        if args.facts_input is not None
        else runtime_facts(args)
    )
    generated = render_rust(parse_facts(facts, count))
    if args.check:
        return 0 if check_output(args.output, generated) else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
