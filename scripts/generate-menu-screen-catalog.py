#!/usr/bin/env python3
"""Generate the Vanilla 26.1 menu-type to client-screen catalog."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from gameplay_id_catalog_extractor import menu_type_entries
from menu_screen_catalog_extractor import (
    MenuScreenRegistration,
    menu_screen_registrations,
)
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_ROOT = Path.home() / "Work/mc-code/sources/26.1"
DEFAULT_OUTPUT = (
    REPO_ROOT / "crates/bbb-native/src/input/inventory/menu_screens_26_1.rs"
)
MENU_TYPES_SOURCE = Path("net/minecraft/world/inventory/MenuType.java")
MENU_SCREENS_SOURCE = Path("net/minecraft/client/gui/screens/MenuScreens.java")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, default=DEFAULT_SOURCE_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def rust_variant(screen_class: str) -> str:
    if not screen_class.endswith("Screen"):
        raise ValueError(f"screen class lacks Screen suffix: {screen_class}")
    return screen_class.removesuffix("Screen")


def render_catalog(entries: list[MenuScreenRegistration]) -> str:
    variants = list(dict.fromkeys(rust_variant(entry.screen_class) for entry in entries))
    lines = [
        "// @generated by scripts/generate-menu-screen-catalog.py; do not edit manually.",
        "// Source: Vanilla 26.1 MenuScreens.java register calls and MenuType.java order.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-menu-screen-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-menu-screen-catalog.py --check",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub(super) enum VanillaMenuScreenKind {",
    ]
    lines.extend(f"    {variant}," for variant in variants)
    lines.extend(
        [
            "}",
            "",
            "pub(super) fn vanilla_menu_screen_kind(",
            "    menu_type_id: i32,",
            ") -> Option<VanillaMenuScreenKind> {",
            "    Some(match menu_type_id {",
        ]
    )
    for entry in entries:
        lines.append(
            f"        {entry.menu_id} => VanillaMenuScreenKind::{rust_variant(entry.screen_class)},"
        )
    lines.extend(
        [
            "        _ => return None,",
            "    })",
            "}",
            "",
            "#[cfg(test)]",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "struct VanillaMenuScreenRegistration {",
            "    menu_id: i32,",
            "    menu_constant: &'static str,",
            "    resource_id: &'static str,",
            "    screen_class: &'static str,",
            "    kind: VanillaMenuScreenKind,",
            "}",
            "",
            "#[cfg(test)]",
            f"const VANILLA_MENU_SCREEN_REGISTRATIONS: [VanillaMenuScreenRegistration; {len(entries)}] = [",
        ]
    )
    for entry in entries:
        lines.extend(
            [
                "    VanillaMenuScreenRegistration {",
                f"        menu_id: {entry.menu_id},",
                f'        menu_constant: "{entry.menu_constant}",',
                f'        resource_id: "{entry.resource_id}",',
                f'        screen_class: "{entry.screen_class}",',
                f"        kind: VanillaMenuScreenKind::{rust_variant(entry.screen_class)},",
                "    },",
            ]
        )
    lines.extend(
        [
            "];",
            "",
            "#[cfg(test)]",
            "mod tests {",
            "    use std::collections::BTreeSet;",
            "",
            "    use bbb_protocol::menu_types::VANILLA_MENU_TYPES;",
            "",
            "    use super::*;",
            "",
            "    #[test]",
            "    fn menu_screen_catalog_exactly_covers_generated_menu_registry() {",
            f"        assert_eq!(VANILLA_MENU_SCREEN_REGISTRATIONS.len(), {len(entries)});",
            "        assert_eq!(VANILLA_MENU_TYPES.len(), VANILLA_MENU_SCREEN_REGISTRATIONS.len());",
            "        let mut constants = BTreeSet::new();",
            "        for (menu_type, registration) in VANILLA_MENU_TYPES",
            "            .iter()",
            "            .zip(VANILLA_MENU_SCREEN_REGISTRATIONS)",
            "        {",
            "            assert_eq!(registration.menu_id, menu_type.id);",
            "            assert_eq!(registration.menu_constant, menu_type.constant_name);",
            "            assert_eq!(registration.resource_id, menu_type.resource_id);",
            "            assert_eq!(",
            "                vanilla_menu_screen_kind(menu_type.id),",
            "                Some(registration.kind),",
            "                \"{} must resolve through the generated screen catalog\",",
            "                registration.screen_class",
            "            );",
            "            assert!(constants.insert(registration.menu_constant));",
            "        }",
            "        assert_eq!(vanilla_menu_screen_kind(-1), None);",
            "        assert_eq!(vanilla_menu_screen_kind(i32::MAX), None);",
            "    }",
            "",
            "    #[test]",
            "    fn native_layout_has_one_generated_screen_kind_resolver() {",
            "        let layout = include_str!(\"layout.rs\");",
            "        let projection = layout",
            "            .split(\"fn inventory_screen_layout_with_recipe_book_mode(\")",
            "            .nth(1)",
            "            .and_then(|source| source.split(\"pub(crate) fn recipe_book_main_gui_offset(\").next())",
            "            .expect(\"inventory screen layout projection\");",
            "        assert_eq!(projection.matches(\"vanilla_menu_screen_kind(menu_type_id)\").count(), 1);",
            "        assert!(!projection.contains(\"VANILLA_MENU_TYPE_\"));",
            "        assert!(!projection.contains(\"menu_type_id ==\"));",
            "        assert!(!projection.contains(\"match menu_type_id\"));",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generated_catalog(source_root: Path) -> str:
    menu_types_source = parse_source(
        MENU_TYPES_SOURCE.as_posix(), (source_root / MENU_TYPES_SOURCE).read_bytes()
    )
    menu_screens_source = parse_source(
        MENU_SCREENS_SOURCE.as_posix(), (source_root / MENU_SCREENS_SOURCE).read_bytes()
    )
    rendered = render_catalog(
        menu_screen_registrations(
            menu_screens_source, menu_type_entries(menu_types_source)
        )
    )
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=rendered,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> int:
    args = parse_args()
    generated = generated_catalog(args.source_root)
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        if current == generated:
            return 0
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile="generated",
            )
        )
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
