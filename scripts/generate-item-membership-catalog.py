#!/usr/bin/env python3
"""Generate checked-in vanilla 26.1 item membership catalogs."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from item_membership_catalog_extractor import (
    brewing_membership,
    menu_membership,
)
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_ROOT = Path.home() / "Work/mc-code/sources/26.1"
DEFAULT_OUTPUT = (
    REPO_ROOT / "crates/bbb-item-model/src/item_runtime/item_membership_catalog.rs"
)
SOURCES = {
    "potion_brewing": Path("net/minecraft/world/item/alchemy/PotionBrewing.java"),
    "brewing_menu": Path("net/minecraft/world/inventory/BrewingStandMenu.java"),
    "items": Path("net/minecraft/world/item/Items.java"),
    "blocks": Path("net/minecraft/world/level/block/Blocks.java"),
    "enchantment_menu": Path("net/minecraft/world/inventory/EnchantmentMenu.java"),
    "cartography_menu": Path(
        "net/minecraft/world/inventory/CartographyTableMenu.java"
    ),
}
def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, default=DEFAULT_SOURCE_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def parse_java(source_root: Path, relative_path: Path):
    return parse_source(relative_path.as_posix(), (source_root / relative_path).read_bytes())


def render_array(name: str, values: tuple[str, ...]) -> list[str]:
    return [
        f"pub(super) const {name}: &[&str] = &[",
        *(f'    "{value}",' for value in values),
        "];",
        "",
    ]


def generate(source_root: Path) -> str:
    sources = {
        name: parse_java(source_root, relative_path)
        for name, relative_path in SOURCES.items()
    }
    brewing = brewing_membership(
        sources["potion_brewing"],
        sources["brewing_menu"],
        sources["items"],
        sources["blocks"],
    )
    menus = menu_membership(
        sources["enchantment_menu"],
        sources["cartography_menu"],
        sources["items"],
        sources["blocks"],
    )
    lines = [
        "// @generated by scripts/generate-item-membership-catalog.py; do not edit manually.",
        "// Source: vanilla 26.1 menu predicates and pure builder declarations.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-item-membership-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-item-membership-catalog.py --check",
        "",
    ]
    lines.extend(render_array("BREWING_POTION_ITEM_IDS", brewing.potion_slot_item_ids))
    lines.extend(
        render_array("BREWING_INGREDIENT_ITEM_IDS", brewing.ingredient_item_ids)
    )
    lines.extend(
        render_array(
            "ENCHANTMENT_LAPIS_LAZULI_ITEM_IDS",
            menus.enchantment_lapis_item_ids,
        )
    )
    lines.extend(
        render_array(
            "CARTOGRAPHY_ADDITIONAL_ITEM_IDS",
            menus.cartography_additional_item_ids,
        )
    )
    lines.extend(
        (
            "#[cfg(test)]",
            "mod tests {",
            "    use std::{collections::HashSet, fs, path::Path};",
            "",
            "    use super::*;",
            "",
            "    #[test]",
            "    fn generated_item_memberships_are_complete_and_unique() {",
            "        assert_eq!(BREWING_POTION_ITEM_IDS.len(), 4);",
            "        assert_eq!(BREWING_INGREDIENT_ITEM_IDS.len(), 21);",
            "        assert_eq!(ENCHANTMENT_LAPIS_LAZULI_ITEM_IDS, &[\"minecraft:lapis_lazuli\"]);",
            "        assert_eq!(CARTOGRAPHY_ADDITIONAL_ITEM_IDS, &[\"minecraft:paper\", \"minecraft:map\", \"minecraft:glass_pane\"]);",
            "        assert_eq!(BREWING_POTION_ITEM_IDS.iter().copied().collect::<HashSet<_>>().len(), 4);",
            "        assert_eq!(BREWING_INGREDIENT_ITEM_IDS.iter().copied().collect::<HashSet<_>>().len(), 21);",
            '        assert_eq!(BREWING_POTION_ITEM_IDS.last(), Some(&"minecraft:glass_bottle"));',
            '        assert_eq!(BREWING_INGREDIENT_ITEM_IDS.last(), Some(&"minecraft:phantom_membrane"));',
            "    }",
            "",
            "    #[test]",
            "    fn production_sources_do_not_redeclare_item_memberships() {",
            "        fn has_all_resource_literals(source: &str, resources: &[&str]) -> bool {",
            "            resources.iter().all(|resource| source.contains(&format!(\"\\\"{resource}\\\"\")))",
            "        }",
            "",
            "        fn visit(directory: &Path, violations: &mut Vec<String>) {",
            "            for entry in fs::read_dir(directory).unwrap() {",
            "                let path = entry.unwrap().path();",
            "                if path.is_dir() { visit(&path, violations); continue; }",
            "                if path.extension().and_then(|value| value.to_str()) != Some(\"rs\") { continue; }",
            "                let display = path.to_string_lossy();",
            "                if display.ends_with(\"/item_membership_catalog.rs\") || display.ends_with(\"/tests.rs\") || display.contains(\"/tests/\") { continue; }",
            "                let source = fs::read_to_string(&path).unwrap();",
            "                let production = source.split(\"#[cfg(test)]\").next().unwrap_or(&source);",
            "                if production.trim_start().starts_with(\"// @generated\") { continue; }",
            "                for line in production.lines().filter(|line| line.contains(\"const \" ) || line.contains(\"static \")) {",
            "                    let upper = line.to_ascii_uppercase();",
            "                    let redeclares = [",
            "                        &[\"BREWING\", \"POTION\", \"ITEM\"][..],",
            "                        &[\"BREWING\", \"INGREDIENT\", \"ITEM\"][..],",
            "                        &[\"ENCHANT\", \"LAPIS\", \"ITEM\"][..],",
            "                        &[\"CARTOGRAPH\", \"ADDITIONAL\", \"ITEM\"][..],",
            "                    ].iter().any(|words| words.iter().all(|word| upper.contains(word)));",
            "                    if redeclares { violations.push(format!(\"{}: parallel item membership declaration `{}`\", display, line.trim())); }",
            "                }",
            "                for (name, resources) in [",
            "                    (\"brewing potion\", BREWING_POTION_ITEM_IDS),",
            "                    (\"brewing ingredient\", BREWING_INGREDIENT_ITEM_IDS),",
            "                ] {",
            "                    if has_all_resource_literals(production, resources) { violations.push(format!(\"{}: parallel {name} resource membership\", display)); }",
            "                }",
            "            }",
            "        }",
            "",
            "        let mut violations = Vec::new();",
            "        visit(Path::new(env!(\"CARGO_MANIFEST_DIR\")).parent().unwrap(), &mut violations);",
            "        assert!(violations.is_empty(), \"parallel item memberships:\\n{}\", violations.join(\"\\n\"));",
            "    }",
            "}",
            "",
        )
    )
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    )
    return formatted.stdout


def check_generated(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    generated = generate(args.source_root)
    if args.check:
        return 0 if check_generated(args.output, generated) else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
