#!/usr/bin/env python3
"""Generate the Vanilla STATIC raw-ID catalog with the official report provider."""

from __future__ import annotations

import argparse
import difflib
import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from bbb_tools.vanilla.arguments import (
    add_vanilla_runtime,
    resolve_runtime_inputs,
    resolve_source_root,
)
from registry_data_catalog_extractor import built_in_registry_catalog, static_registry_elements
from vanilla_java_source import parse_source

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "crates/bbb-facts/src/static_registry_elements.rs"
DEFAULT_BIN_OUTPUT = REPO_ROOT / "crates/bbb-facts/data/static_registry_elements_26_1.bin"


def parse_java(source_root: Path, relative_path: str):
    return parse_source(relative_path, (source_root / relative_path).read_bytes())


def format_rust(source: str) -> str:
    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=source,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def static_registry_runtime_report(args: argparse.Namespace) -> str:
    resolve_runtime_inputs(args)
    jars = [args.client_jar, *sorted(args.libraries_root.rglob("*.jar"))]
    classpath = os.pathsep.join(str(path) for path in jars)
    with tempfile.TemporaryDirectory(prefix="bbb-static-registry-report-") as directory:
        root = Path(directory)
        subprocess.run(
            [
                str(args.javac),
                "-cp",
                classpath,
                "-d",
                str(root),
                str(REPO_ROOT / "scripts/vanilla-runtime/StaticRegistryReport.java"),
            ],
            check=True,
        )
        result = subprocess.run(
            [
                str(args.java),
                "-cp",
                os.pathsep.join((str(root), classpath)),
                "StaticRegistryReport",
                str(root),
            ],
            cwd=root,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            raise RuntimeError("Vanilla registry report failed:\n" + result.stderr + result.stdout)
        return (root / "reports/registries.json").read_text()


def _pack_tables(entries) -> tuple[bytes, int, int, int, int]:
    str_bytes = bytearray()
    str_spans: dict[str, tuple[int, int]] = {}

    def intern(text: str) -> tuple[int, int]:
        span = str_spans.get(text)
        if span is None:
            encoded = text.encode("utf-8")
            if not encoded.isascii():
                raise ValueError(f"non-ASCII static registry string: {text!r}")
            if len(encoded) > 0xFFFF:
                raise ValueError("static registry string exceeds u16 bytes")
            span = (len(str_bytes), len(encoded))
            str_bytes.extend(encoded)
            str_spans[text] = span
        return span

    element_spans: list[tuple[int, int]] = []
    registry_records: list[tuple[int, int, int, int]] = []
    for entry in entries:
        reg_off, reg_len = intern(entry.resource_id)
        elem_start = len(element_spans)
        for resource_id in entry.elements:
            element_spans.append(intern(resource_id))
        registry_records.append((reg_off, reg_len, elem_start, len(entry.elements)))

    out = bytearray(str_bytes)
    elements_offset = len(out)
    for off, length in element_spans:
        out.extend(struct.pack("<IH", off, length))
    registries_offset = len(out)
    for reg_off, reg_len, elem_start, elem_len in registry_records:
        out.extend(struct.pack("<IHII", reg_off, reg_len, elem_start, elem_len))

    return (
        bytes(out),
        len(element_spans),
        len(registry_records),
        elements_offset,
        registries_offset,
    )


def pack_static_registry_elements(entries) -> bytes:
    return _pack_tables(entries)[0]


def render_static_registry_elements(
    entries,
    bin_rel_path: str = "../data/static_registry_elements_26_1.bin",
) -> str:
    (
        _blob,
        element_count,
        registry_count,
        elements_offset,
        registries_offset,
    ) = _pack_tables(entries)
    lines = [
        "// @generated by scripts/generate-static-registry-catalog.py",
        "// RegistryDumpReport.java:37-45;"
        " BuiltInRegistries registration identities/order checked by CST.",
        f'const BYTES: &[u8] = include_bytes!("{bin_rel_path}");',
        f"const ELEMENT_COUNT: usize = {element_count};",
        f"const REGISTRY_COUNT: usize = {registry_count};",
        f"const ELEMENTS_OFFSET: usize = {elements_offset};",
        f"const REGISTRIES_OFFSET: usize = {registries_offset};",
        "const STRINGS_END: usize = ELEMENTS_OFFSET;",
        "",
        "const _: () = {",
        "    let mut i = 0;",
        "    while i + 8 <= STRINGS_END {",
        "        let word = u64::from_ne_bytes([",
        "            BYTES[i],",
        "            BYTES[i + 1],",
        "            BYTES[i + 2],",
        "            BYTES[i + 3],",
        "            BYTES[i + 4],",
        "            BYTES[i + 5],",
        "            BYTES[i + 6],",
        "            BYTES[i + 7],",
        "        ]);",
        "        assert!(word & 0x8080_8080_8080_8080 == 0);",
        "        i += 8;",
        "    }",
        "    while i < STRINGS_END {",
        "        assert!(BYTES[i] < 0x80);",
        "        i += 1;",
        "    }",
        "};",
        "",
        "macro_rules! u16_at {",
        "    ($offset:expr) => {{",
        "        let off = $offset;",
        "        u16::from_le_bytes([BYTES[off], BYTES[off + 1]])",
        "    }};",
        "}",
        "",
        "macro_rules! u32_at {",
        "    ($offset:expr) => {{",
        "        let off = $offset;",
        "        u32::from_le_bytes([",
        "            BYTES[off],",
        "            BYTES[off + 1],",
        "            BYTES[off + 2],",
        "            BYTES[off + 3],",
        "        ])",
        "    }};",
        "}",
        "",
        "macro_rules! str_at {",
        "    ($offset:expr, $len:expr) => {{",
        "        let off: usize = $offset;",
        "        let len: usize = $len;",
        "        assert!(off + len <= STRINGS_END);",
        "        // SAFETY: `BYTES[..STRINGS_END]` is verified ASCII above and `off + len`",
        "        // is bounded within `BYTES`.",
        "        unsafe {",
        "            core::str::from_utf8_unchecked(core::slice::from_raw_parts(",
        "                BYTES.as_ptr().add(off),",
        "                len,",
        "            ))",
        "        }",
        "    }};",
        "}",
        "",
        "const fn decode_elements_pool() -> [&'static str; ELEMENT_COUNT] {",
        '    let mut out = [""; ELEMENT_COUNT];',
        "    let mut idx = 0;",
        "    while idx < ELEMENT_COUNT {",
        "        let base = ELEMENTS_OFFSET + idx * 6;",
        "        out[idx] = str_at!(u32_at!(base) as usize, u16_at!(base + 4) as usize);",
        "        idx += 1;",
        "    }",
        "    out",
        "}",
        "",
        "static DECODED_ELEMENTS_POOL: [&str; ELEMENT_COUNT] = decode_elements_pool();",
        "",
        "const fn decode_registries() -> [(&'static str, &'static [&'static str]);"
        " REGISTRY_COUNT] {",
        '    let mut out: [(&str, &[&str]); REGISTRY_COUNT] = [("", &[]); REGISTRY_COUNT];',
        "    let mut idx = 0;",
        "    while idx < REGISTRY_COUNT {",
        "        let base = REGISTRIES_OFFSET + idx * 14;",
        "        let registry_id = str_at!(u32_at!(base) as usize, u16_at!(base + 4) as usize);",
        "        let elem_start = u32_at!(base + 6) as usize;",
        "        let elem_len = u32_at!(base + 10) as usize;",
        "        let elements: &'static [&'static str] = if elem_len == 0 {",
        "            &[]",
        "        } else {",
        "            assert!(elem_start + elem_len <= ELEMENT_COUNT);",
        "            // SAFETY: `elem_start + elem_len <= ELEMENT_COUNT` bounds the slice",
        "            // within `DECODED_ELEMENTS_POOL`.",
        "            unsafe {",
        "                core::slice::from_raw_parts(",
        "                    DECODED_ELEMENTS_POOL.as_ptr().add(elem_start),",
        "                    elem_len,",
        "                )",
        "            }",
        "        };",
        "        out[idx] = (registry_id, elements);",
        "        idx += 1;",
        "    }",
        "    out",
        "}",
        "",
        "static DECODED_REGISTRIES: [(&str, &[&str]); REGISTRY_COUNT] = decode_registries();",
        "pub const VANILLA_STATIC_REGISTRY_ELEMENTS: &[(&str, &[&str])] = &DECODED_REGISTRIES;",
        "",
        "#[inline]",
        "pub fn vanilla_static_registry_elements(registry: &str) -> Option<&'static [&'static str]> {",
        "    crate::lookup_tables::static_registry_elements(registry)",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    add_vanilla_runtime(parser)
    parser.add_argument("--facts-input", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--bin-output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source_root = resolve_source_root(args)
    expected = built_in_registry_catalog(
        parse_java(source_root, "net/minecraft/core/registries/BuiltInRegistries.java"),
        parse_java(source_root, "net/minecraft/core/registries/Registries.java"),
    )
    report = (
        args.facts_input.read_text()
        if args.facts_input is not None
        else static_registry_runtime_report(args)
    )
    entries = static_registry_elements(report, expected)
    bin_output = args.bin_output
    if bin_output is None:
        bin_output = (
            DEFAULT_BIN_OUTPUT if args.output == DEFAULT_OUTPUT else args.output.with_suffix(".bin")
        )
    bin_rel = os.path.relpath(bin_output, args.output.parent).replace("\\", "/")
    generated = format_rust(render_static_registry_elements(entries, bin_rel))
    blob = pack_static_registry_elements(entries)
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        current_bin = bin_output.read_bytes() if bin_output.exists() else b""
        ok = True
        if generated != current:
            sys.stderr.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    generated.splitlines(keepends=True),
                    fromfile=str(args.output),
                    tofile="generated",
                )
            )
            ok = False
        if blob != current_bin:
            sys.stderr.write(
                f"binary output differs at {bin_output} "
                f"(actual {len(current_bin)} B vs expected {len(blob)} B)\n"
            )
            ok = False
        return 0 if ok else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    bin_output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    bin_output.write_bytes(blob)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
