#!/usr/bin/env python3
"""Generate the checked-in vanilla 26.1 command argument type catalog."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from command_argument_catalog_extractor import command_argument_entries
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_ROOT = Path.home() / "Work/mc-code/sources/26.1"
DEFAULT_OUTPUT = REPO_ROOT / "crates/bbb-protocol/src/packets/commands/generated_26_1.rs"
SOURCE = Path("net/minecraft/commands/synchronization/ArgumentTypeInfos.java")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, default=DEFAULT_SOURCE_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def generate(source_root: Path) -> str:
    source = parse_source(SOURCE.as_posix(), (source_root / SOURCE).read_bytes())
    entries = command_argument_entries(source)
    lines = [
        "// @generated by scripts/generate-command-argument-catalog.py; do not edit manually.",
        "// Source: vanilla 26.1 ArgumentTypeInfos.bootstrap registration order.",
        "// Update: scripts/vanilla-source-tools.sh python scripts/generate-command-argument-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh python scripts/generate-command-argument-catalog.py --check",
        "",
        "pub(super) const COMMAND_ARGUMENT_PARSERS: &[&str] = &[",
        *(f'    "{entry.resource_id}",' for entry in entries),
        "];",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    #[test]",
        "    fn command_argument_order_matches_vanilla_26_1() {",
        "        assert_eq!(COMMAND_ARGUMENT_PARSERS.len(), 57);",
        '        assert_eq!(COMMAND_ARGUMENT_PARSERS.first(), Some(&"brigadier:bool"));',
        '        assert_eq!(COMMAND_ARGUMENT_PARSERS.last(), Some(&"minecraft:uuid"));',
        "    }",
        "}",
        "",
    ]
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines), text=True, capture_output=True, check=True,
    ).stdout


def main() -> int:
    args = parse_args()
    generated = generate(args.source_root)
    current = args.output.read_text() if args.output.exists() else ""
    if args.check:
        if current == generated:
            return 0
        sys.stderr.writelines(difflib.unified_diff(current.splitlines(True), generated.splitlines(True), fromfile=str(args.output), tofile="generated"))
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
