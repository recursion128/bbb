#!/usr/bin/env python3
"""Generate/check the checked-in vanilla 26.1 entity renderer catalog."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root
from core_registry_catalog_extractor import entity_type_entries, vec3_constant
from entity_renderer_catalog_extractor import (
    extract_avatar_renderer_shadow,
    extract_entity_renderer_registrations,
    extract_living_entity_upside_down_names,
)
from vanilla_java_source import parse_source

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/bbb-client-world/src/entities/renderer_catalog/generated_26_1.rs"
)
ENTITY_TYPE_SOURCE = Path("net/minecraft/world/entity/EntityType.java")
AVATAR_SOURCE = Path("net/minecraft/world/entity/Avatar.java")
ENTITY_RENDERERS_SOURCE = Path(
    "net/minecraft/client/renderer/entity/EntityRenderers.java"
)
RENDERER_SOURCE_DIR = Path("net/minecraft/client/renderer/entity")
LIVING_ENTITY_RENDERER_SOURCE = RENDERER_SOURCE_DIR / "LivingEntityRenderer.java"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.source_root = resolve_source_root(args)
    return args


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(source_root: Path) -> str:
    def parse(relative_path: Path):
        return parse_source(
            relative_path.as_posix(), (source_root / relative_path).read_bytes()
        )

    avatar = parse(AVATAR_SOURCE)
    entity_types = entity_type_entries(
        parse(ENTITY_TYPE_SOURCE),
        named_vec3_constants={
            "Avatar.DEFAULT_VEHICLE_ATTACHMENT": vec3_constant(
                avatar, "DEFAULT_VEHICLE_ATTACHMENT"
            )
        },
    )
    entity_renderers = parse(ENTITY_RENDERERS_SOURCE)
    renderer_sources = [
        parse(path.relative_to(source_root))
        for path in sorted((source_root / RENDERER_SOURCE_DIR).rglob("*.java"))
        if path != source_root / ENTITY_RENDERERS_SOURCE
    ]
    registrations = extract_entity_renderer_registrations(
        entity_renderers,
        renderer_sources,
        [entry.constant_name for entry in entity_types],
    )
    avatar_shadow_radius_bits, avatar_shadow_strength_bits = (
        extract_avatar_renderer_shadow(renderer_sources)
    )
    living_entity_renderer_sources = [
        source
        for source in renderer_sources
        if source.relative_path == LIVING_ENTITY_RENDERER_SOURCE.as_posix()
    ]
    if len(living_entity_renderer_sources) != 1:
        raise ValueError("expected one LivingEntityRenderer source")
    upside_down_names = extract_living_entity_upside_down_names(
        living_entity_renderer_sources[0]
    )
    upside_down_names_rust = ", ".join(rust_string(name) for name in upside_down_names)
    lines = [
        "// @generated by scripts/generate-entity-renderer-catalog.py; do not edit manually.",
        "// Sources: vanilla 26.1 EntityType.java, EntityRenderers.java, and registered renderer classes.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-entity-renderer-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-entity-renderer-catalog.py --check",
        "",
        "pub(super) const VANILLA_LIVING_ENTITY_RENDERER_UPSIDE_DOWN_NAMES_26_1: &[&str] = &[",
    ]
    for name in upside_down_names:
        lines.append(f"    {rust_string(name)},")
    lines.extend(
        [
            "];",
            "",
            f"pub(super) const VANILLA_AVATAR_RENDERER_SHADOW_RADIUS_BITS_26_1: u32 = {avatar_shadow_radius_bits};",
            f"pub(super) const VANILLA_AVATAR_RENDERER_SHADOW_STRENGTH_BITS_26_1: u32 = {avatar_shadow_strength_bits};",
            "",
            "pub(super) const VANILLA_ENTITY_RENDERER_REGISTRATIONS_26_1: &[VanillaEntityRendererRegistration] = &[",
        ]
    )
    for entry in registrations:
        boat_kind = (
            "Some(VanillaBoatRendererKind { "
            f"family: BoatModelFamily::{entry.boat_kind[0]}, "
            f"chest: {str(entry.boat_kind[1]).lower()} }}"
            ")"
            if entry.boat_kind is not None
            else "None"
        )
        lines.extend(
            [
                "    VanillaEntityRendererRegistration {",
                f"        entity_type_id: {entry.entity_type_id},",
                f"        constant_name: {rust_string(entry.constant_name)},",
                f"        renderer_class: {rust_string(entry.renderer_class)},",
                "        static_full_block_light: "
                + str(entry.static_full_block_light).lower()
                + ",",
                "        minimum_block_light: "
                + (
                    f"Some({entry.minimum_block_light})"
                    if entry.minimum_block_light is not None
                    else "None"
                )
                + ",",
                "        thrown_item_scale_bits: "
                + (
                    f"Some({entry.thrown_item_scale_bits})"
                    if entry.thrown_item_scale_bits is not None
                    else "None"
                )
                + ",",
                f"        shadow_radius_bits: {entry.shadow_radius_bits},",
                f"        shadow_strength_bits: {entry.shadow_strength_bits},",
                "        uses_abstract_feline_model: "
                + str(entry.uses_abstract_feline_model).lower()
                + ",",
                "        uses_abstract_horse_renderer: "
                + str(entry.uses_abstract_horse_renderer).lower()
                + ",",
                "        uses_mob_item_in_hand_layer: "
                + str(entry.uses_mob_item_in_hand_layer).lower()
                + ",",
                "        extracts_mob_aggressive: "
                + str(entry.extracts_mob_aggressive).lower()
                + ",",
                "        extracts_unhappy_counter: "
                + str(entry.extracts_unhappy_counter).lower()
                + ",",
                "        extracts_casting_spell: "
                + str(entry.extracts_casting_spell).lower()
                + ",",
                "        extracts_sheep_head_eat: "
                + str(entry.extracts_sheep_head_eat).lower()
                + ",",
                "        extracts_zombie_underwater_converting: "
                + str(entry.extracts_zombie_underwater_converting).lower()
                + ",",
                "        extracts_wolf_sitting: "
                + str(entry.extracts_wolf_sitting).lower()
                + ",",
                "        extracts_parrot_pose: "
                + str(entry.extracts_parrot_pose).lower()
                + ",",
                "        undead_horse_kind: "
                + (
                    f"Some(UndeadHorseModelFamily::{entry.undead_horse_kind})"
                    if entry.undead_horse_kind is not None
                    else "None"
                )
                + ",",
                "        horse_kind: "
                + (
                    f"Some(VanillaHorseRendererKind::{entry.horse_kind})"
                    if entry.horse_kind is not None
                    else "None"
                )
                + ",",
                "        llama_kind: "
                + (
                    f"Some(LlamaModelFamily::{entry.llama_kind})"
                    if entry.llama_kind is not None
                    else "None"
                )
                + ",",
                f"        boat_kind: {boat_kind},",
                "        piglin_kind: "
                + (
                    f"Some(PiglinModelFamily::{entry.piglin_kind})"
                    if entry.piglin_kind is not None
                    else "None"
                )
                + ",",
                "    },",
            ]
        )
    lines.extend(
        [
            "];",
            "",
            "#[cfg(test)]",
            "mod generated_catalog_guards {",
            "    #[test]",
            "    fn living_entity_upside_down_names_match_vanilla_renderer() {",
            f"        assert_eq!(super::VANILLA_LIVING_ENTITY_RENDERER_UPSIDE_DOWN_NAMES_26_1, &[{upside_down_names_rust}]);",
            "        for name in super::VANILLA_LIVING_ENTITY_RENDERER_UPSIDE_DOWN_NAMES_26_1 {",
            "            assert!(super::vanilla_living_entity_renderer_name_is_upside_down(name));",
            "        }",
            '        assert!(!super::vanilla_living_entity_renderer_name_is_upside_down("dinnerbone"));',
            "    }",
            "}",
            "",
        ]
    )
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    )
    return formatted.stdout


def main() -> int:
    args = parse_args()
    generated = render(args.source_root)
    current = args.output.read_text() if args.output.exists() else ""
    if args.check:
        if current == generated:
            return 0
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile=str(args.output) + " (generated)",
            )
        )
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
