#!/usr/bin/env python3
"""Generate/check the checked-in vanilla 26.1 entity renderer catalog."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from core_registry_catalog_extractor import entity_type_entries
from entity_renderer_catalog_extractor import extract_entity_renderer_registrations
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_ROOT = Path.home() / "Work/mc-code/sources/26.1"
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/bbb-world/src/entities/renderer_catalog/generated_26_1.rs"
)
ENTITY_TYPE_SOURCE = Path("net/minecraft/world/entity/EntityType.java")
ENTITY_RENDERERS_SOURCE = Path(
    "net/minecraft/client/renderer/entity/EntityRenderers.java"
)
RENDERER_SOURCE_DIR = Path("net/minecraft/client/renderer/entity")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, default=DEFAULT_SOURCE_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(source_root: Path) -> str:
    def parse(relative_path: Path):
        return parse_source(
            relative_path.as_posix(), (source_root / relative_path).read_bytes()
        )

    entity_types = entity_type_entries(parse(ENTITY_TYPE_SOURCE))
    entity_renderers = parse(ENTITY_RENDERERS_SOURCE)
    renderer_sources = [
        parse(path.relative_to(source_root))
        for path in sorted((source_root / RENDERER_SOURCE_DIR).rglob("*.java"))
        if path != source_root / ENTITY_RENDERERS_SOURCE
    ]
    registrations = extract_entity_renderer_registrations(
        entity_renderers,
        renderer_sources,
        [entry.constant_name for entry in entity_types],
    )
    lines = [
        "// @generated by scripts/generate-entity-renderer-catalog.py; do not edit manually.",
        "// Sources: vanilla 26.1 EntityType.java, EntityRenderers.java, and registered renderer classes.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-entity-renderer-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-entity-renderer-catalog.py --check",
        "",
        "pub(super) const VANILLA_ENTITY_RENDERER_REGISTRATIONS_26_1: &[VanillaEntityRendererRegistration] = &[",
    ]
    for entry in registrations:
        lines.extend(
            [
                "    VanillaEntityRendererRegistration {",
                f"        entity_type_id: {entry.entity_type_id},",
                f"        constant_name: {rust_string(entry.constant_name)},",
                f"        renderer_class: {rust_string(entry.renderer_class)},",
                "        static_full_block_light: "
                + str(entry.static_full_block_light).lower()
                + ",",
                "        thrown_item_scale_bits: "
                + (
                    f"Some({entry.thrown_item_scale_bits})"
                    if entry.thrown_item_scale_bits is not None
                    else "None"
                )
                + ",",
                "        uses_abstract_feline_model: "
                + str(entry.uses_abstract_feline_model).lower()
                + ",",
                "        uses_abstract_horse_renderer: "
                + str(entry.uses_abstract_horse_renderer).lower()
                + ",",
                "        uses_mob_item_in_hand_layer: "
                + str(entry.uses_mob_item_in_hand_layer).lower()
                + ",",
                "        extracts_mob_aggressive: "
                + str(entry.extracts_mob_aggressive).lower()
                + ",",
                "        extracts_unhappy_counter: "
                + str(entry.extracts_unhappy_counter).lower()
                + ",",
                "        extracts_casting_spell: "
                + str(entry.extracts_casting_spell).lower()
                + ",",
                "    },",
            ]
        )
    lines.extend(
        [
            "];",
            "",
            "#[cfg(test)]",
            "mod generated_catalog_guards {",
            "    #[test]",
            "    fn native_light_projection_does_not_restore_static_full_bright_membership() {",
            '        let source = include_str!("../../../../bbb-native/src/entity_scene/instance.rs");',
            '        assert!(!source.contains("VANILLA_ENTITY_TYPE_BLAZE_ID"));',
            "    }",
            "",
            "    #[test]",
            "    fn native_model_selection_does_not_restore_noop_renderer_membership() {",
            '        let source = include_str!("../../../../bbb-native/src/entity_scene/kind.rs");',
            '        assert!(!source.contains("VANILLA_ENTITY_TYPE_AREA_EFFECT_CLOUD_ID"));',
            "    }",
            "",
            "    #[test]",
            "    fn world_projection_does_not_restore_feline_type_membership() {",
            '        let source = include_str!("../dimensions.rs");',
            '        assert!(!source.contains("fn vanilla_feline_family"));',
            "    }",
            "",
            "    #[test]",
            "    fn world_projection_does_not_restore_equine_renderer_memberships() {",
            '        let animations = include_str!("../animations.rs");',
            '        let dimensions = include_str!("../dimensions.rs");',
            '        let store = include_str!("../store.rs");',
            '        assert!(!animations.contains("fn vanilla_equine_type"));',
            '        assert!(!dimensions.contains("fn is_vanilla_rearing_horse_passenger_attachment_type"));',
            '        assert!(!store.contains("fn vanilla_equine_saddle_type"));',
            "    }",
            "",
            "    #[test]",
            "    fn world_projection_does_not_restore_mob_item_in_hand_membership() {",
            '        let source = include_str!("../store.rs");',
            '        assert!(!source.contains("fn vanilla_mob_item_in_hand_layer_type"));',
            "    }",
            "",
            "    #[test]",
            "    fn world_projection_does_not_restore_aggressive_renderer_memberships() {",
            '        let source = include_str!("../dimensions.rs");',
            '        assert!(!source.contains("fn vanilla_zombie_model_family"));',
            '        assert!(!source.contains("fn vanilla_piglin_melee_attack_family"));',
            '        assert!(!source.contains("fn vanilla_illager_aggressive_arm_pose_family"));',
            "    }",
            "",
            "    #[test]",
            "    fn world_projection_does_not_restore_villager_unhappy_membership() {",
            '        let source = include_str!("../store.rs");',
            '        assert!(!source.contains("let villager_unhappy = matches!"));',
            "    }",
            "",
            "    #[test]",
            "    fn native_projection_does_not_restore_spellcaster_illager_membership() {",
            '        let source = include_str!("../../../../bbb-native/src/entity_scene/variants.rs");',
            '        assert!(!source.contains("fn illager_spellcasting"));',
            "    }",
            "",
            "    #[test]",
            "    fn native_thrown_item_projection_does_not_restore_renderer_table() {",
            '        let scene = include_str!("../../../../bbb-native/src/entity_scene.rs");',
            '        assert!(!scene.contains("THROWN_ITEM_PROJECTILE_BILLBOARDS"));',
            '        let billboards = include_str!("../../../../bbb-native/src/item_entities.rs");',
            '        assert!(billboards.contains("vanilla_entity_renderer_thrown_item_scales"));',
            '        let kinds = include_str!("../../../../bbb-native/src/entity_scene/kind.rs");',
            '        assert!(kinds.contains("vanilla_entity_renderer_thrown_item_scale"));',
            '        for removed in [',
            '            "VANILLA_ENTITY_TYPE_EGG_ID",',
            '            "VANILLA_ENTITY_TYPE_ENDER_PEARL_ID",',
            '            "VANILLA_ENTITY_TYPE_EXPERIENCE_BOTTLE_ID",',
            '            "VANILLA_ENTITY_TYPE_EYE_OF_ENDER_ID",',
            '            "VANILLA_ENTITY_TYPE_FIREBALL_ID",',
            '            "VANILLA_ENTITY_TYPE_LINGERING_POTION_ID",',
            '            "VANILLA_ENTITY_TYPE_SMALL_FIREBALL_ID",',
            '            "VANILLA_ENTITY_TYPE_SNOWBALL_ID",',
            '            "VANILLA_ENTITY_TYPE_SPLASH_POTION_ID",',
            '        ] {',
            '            assert!(!kinds.contains(removed), "restored {removed}");',
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    )
    return formatted.stdout


def main() -> int:
    args = parse_args()
    generated = render(args.source_root)
    current = args.output.read_text() if args.output.exists() else ""
    if args.check:
        if current == generated:
            return 0
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile=str(args.output) + " (generated)",
            )
        )
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
