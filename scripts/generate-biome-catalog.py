#!/usr/bin/env python3
"""Generate the checked-in vanilla 26.1 biome fallback order."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root

from bootstrap_catalog_extractor import static_register_entries
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "crates/bbb-pack/src/colors/generated_26_1.rs"
BIOMES_SOURCE = Path("net/minecraft/world/level/biome/Biomes.java")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.source_root = resolve_source_root(args)
    return args


def generate(source_root: Path) -> str:
    source = parse_source(
        BIOMES_SOURCE.as_posix(), (source_root / BIOMES_SOURCE).read_bytes()
    )
    entries = static_register_entries(source, "ResourceKey<Biome>", 65)
    stems = [entry.resource_id.removeprefix("minecraft:") for entry in entries]
    lines = [
        "// @generated by scripts/generate-biome-catalog.py; do not edit manually.",
        "// Source: vanilla 26.1 Biomes.java ResourceKey declaration order.",
        "// Update: scripts/vanilla-source-tools.sh python scripts/generate-biome-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh python scripts/generate-biome-catalog.py --check",
        "",
        "pub(crate) const VANILLA_BIOME_ORDER: &[&str] = &[",
        *(f'    "{stem}",' for stem in stems),
        "];",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    #[test]",
        "    fn vanilla_biome_order_matches_26_1_declarations() {",
        "        assert_eq!(VANILLA_BIOME_ORDER.len(), 65);",
        '        assert_eq!(VANILLA_BIOME_ORDER.first(), Some(&"the_void"));',
        '        assert_eq!(VANILLA_BIOME_ORDER.last(), Some(&"end_barrens"));',
        "    }",
        "}",
        "",
    ]
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    )
    return formatted.stdout


def check_generated(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    generated = generate(args.source_root)
    if args.check:
        return 0 if check_generated(args.output, generated) else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
