#!/usr/bin/env python3
"""Generate Vanilla 26.1 environment-attribute declaration metadata."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root
from environment_attribute_catalog_extractor import (
    EnvironmentAttributeEntry,
    EnvironmentAttributeTypeEntry,
    environment_attribute_entries,
    environment_attribute_type_entries,
)
from vanilla_java_source import parse_source

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/bbb-facts/src/environment_attribute_types.rs"
)
SOURCE_PATH = Path("net/minecraft/world/attribute/EnvironmentAttributes.java")
TYPE_SOURCE_PATH = Path("net/minecraft/world/attribute/AttributeTypes.java")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.source_root = resolve_source_root(args)
    return args


def rust_variant(value: str) -> str:
    return "".join(part.title() for part in value.lower().split("_"))


def render_catalog(
    entries: list[EnvironmentAttributeEntry],
    type_entries: list[EnvironmentAttributeTypeEntry],
) -> str:
    lines = [
        "// @generated by scripts/generate-environment-attribute-catalog.py",
        "// from Vanilla 26.1 EnvironmentAttributes.java and AttributeTypes.java.",
        "// Do not edit by hand.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum VanillaEnvironmentAttributeType {",
    ]
    for value_type in sorted(entry.constant_name for entry in type_entries):
        lines.append(f"    {rust_variant(value_type)},")
    lines.extend(
        [
            "}",
            "",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub enum VanillaEnvironmentModifierFamily {",
        ]
    )
    for family in sorted({entry.modifier_family for entry in type_entries}):
        lines.append(f"    {rust_variant(family)},")
    lines.extend(
        [
            "}",
            "",
            "impl VanillaEnvironmentAttributeType {",
            "    pub const fn modifier_family(self) -> VanillaEnvironmentModifierFamily {",
            "        match self {",
        ]
    )
    for type_entry in type_entries:
        lines.append(
            "            Self::"
            f"{rust_variant(type_entry.constant_name)} => "
            "VanillaEnvironmentModifierFamily::"
            f"{rust_variant(type_entry.modifier_family)},"
        )
    lines.extend(
        [
            "        }",
            "    }",
            "}",
            "",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub enum VanillaEnvironmentAttributeRange {",
        ]
    )
    for value_range in sorted({entry.value_range for entry in entries}):
        lines.append(f"    {rust_variant(value_range)},")
    lines.extend(
        [
            "}",
            "",
            "impl VanillaEnvironmentAttributeRange {",
            "    pub fn accepts_float(self, value: f32) -> bool {",
            "        match self {",
            "            Self::Any => true,",
            "            Self::NonNegativeFloat => (0.0..=f32::INFINITY).contains(&value),",
            "            Self::SkyLight => (0.0..=15.0).contains(&value),",
            "            Self::UnitFloat => (0.0..=1.0).contains(&value),",
            "        }",
            "    }",
            "",
            "    // AttributeRange.java:24-34 preserves NaN.",
            "    pub fn sanitize_float(self, value: f32) -> f32 {",
            "        match self {",
            "            Self::Any => value,",
            "            Self::NonNegativeFloat => value.clamp(0.0, f32::INFINITY),",
            "            Self::SkyLight => value.clamp(0.0, 15.0),",
            "            Self::UnitFloat => value.clamp(0.0, 1.0),",
            "        }",
            "    }",
            "}",
            "",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub enum VanillaEnvironmentScalarValue {",
            "    Boolean(bool),",
            "    FloatBits(u32),",
            "}",
            "",
            "#[cfg(test)]",
            "const VANILLA_ENVIRONMENT_ATTRIBUTE_TYPES: "
            f"[VanillaEnvironmentAttributeType; {len(type_entries)}] = [",
        ]
    )
    for type_entry in type_entries:
        lines.append(
            f"    VanillaEnvironmentAttributeType::{rust_variant(type_entry.constant_name)},"
        )
    lines.extend(
        [
            "];",
            "",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "#[non_exhaustive]",
            "pub struct VanillaEnvironmentAttribute {",
            "    pub resource_id: &'static str,",
            "    pub value_type: VanillaEnvironmentAttributeType,",
            "    pub value_range: VanillaEnvironmentAttributeRange,",
            "    pub scalar_default: Option<VanillaEnvironmentScalarValue>,",
            "    pub color_default: Option<u32>,",
            "    pub syncable: bool,",
            "    pub positional: bool,",
            "    pub spatially_interpolated: bool,",
            "}",
            "",
            "pub const VANILLA_ENVIRONMENT_ATTRIBUTES: "
            f"[VanillaEnvironmentAttribute; {len(entries)}] = [",
        ]
    )
    for entry in entries:
        if entry.scalar_default is None:
            scalar_default = "None"
        elif entry.value_type == "BOOLEAN":
            scalar_default = (
                "Some(VanillaEnvironmentScalarValue::Boolean("
                f"{str(entry.scalar_default).lower()}))"
            )
        else:
            scalar_default = (
                "Some(VanillaEnvironmentScalarValue::FloatBits("
                f"0x{entry.scalar_default:08x}))"
            )
        color_default = (
            "None" if entry.color_default is None else f"Some(0x{entry.color_default:08x})"
        )
        lines.extend(
            [
                "    VanillaEnvironmentAttribute {",
                f'        resource_id: "{entry.resource_id}",',
                "        value_type: "
                f"VanillaEnvironmentAttributeType::{rust_variant(entry.value_type)},",
                "        value_range: "
                f"VanillaEnvironmentAttributeRange::{rust_variant(entry.value_range)},",
                f"        scalar_default: {scalar_default},",
                f"        color_default: {color_default},",
                f"        syncable: {str(entry.syncable).lower()},",
                f"        positional: {str(entry.positional).lower()},",
                "        spatially_interpolated: "
                f"{str(entry.spatially_interpolated).lower()},",
                "    },",
            ]
        )
    lines.extend(
        [
            "];",
            "",
            "pub fn vanilla_environment_attribute(",
            "    resource_id: &str,",
            ") -> Option<&'static VanillaEnvironmentAttribute> {",
            "    VANILLA_ENVIRONMENT_ATTRIBUTES",
            "        .iter()",
            "        .find(|entry| entry.resource_id == resource_id)",
            "}",
            "",
            "#[cfg(test)]",
            "mod tests {",
            "    use super::*;",
            "    use std::collections::BTreeSet;",
            "",
            "    #[test]",
            "    fn environment_attribute_catalog_is_complete_ordered_and_unique() {",
            f"        assert_eq!(VANILLA_ENVIRONMENT_ATTRIBUTES.len(), {len(entries)});",
            "        assert_eq!(",
            "            VANILLA_ENVIRONMENT_ATTRIBUTES",
            "                .iter()",
            "                .map(|entry| entry.resource_id)",
            "                .collect::<BTreeSet<_>>()",
            "                .len(),",
            "            VANILLA_ENVIRONMENT_ATTRIBUTES.len()",
            "        );",
            "    }",
            "",
            "    #[test]",
            "    fn environment_attribute_scalar_defaults_match_types() {",
            "        let mut counts = [0usize; 3];",
            "        for entry in VANILLA_ENVIRONMENT_ATTRIBUTES {",
            "            assert_eq!(entry.color_default.is_some(), matches!(entry.value_type,",
            "                VanillaEnvironmentAttributeType::RgbColor | "
            "VanillaEnvironmentAttributeType::ArgbColor));",
            "            match (entry.value_type, entry.scalar_default) {",
            "                (VanillaEnvironmentAttributeType::Boolean, "
            "Some(VanillaEnvironmentScalarValue::Boolean(_))) => counts[0] += 1,",
            "                (VanillaEnvironmentAttributeType::Float, "
            "Some(VanillaEnvironmentScalarValue::FloatBits(_))) => counts[1] += 1,",
            "                (VanillaEnvironmentAttributeType::AngleDegrees, "
            "Some(VanillaEnvironmentScalarValue::FloatBits(_))) => counts[2] += 1,",
            "                (VanillaEnvironmentAttributeType::Boolean | "
            "VanillaEnvironmentAttributeType::Float | "
            "VanillaEnvironmentAttributeType::AngleDegrees, _) => "
            "panic!(\"missing scalar default\"),",
            "                (_, None) => {},",
            "                _ => panic!(\"unexpected scalar default\"),",
            "            }",
            "        }",
            "        assert_eq!(counts, [13, 14, 3]);",
            "    }",
            "",
            "    #[test]",
            "    fn environment_attribute_catalog_preserves_builder_flags() {",
            "        let fog = vanilla_environment_attribute(",
            '            "minecraft:visual/fog_color",',
            "        )",
            "        .unwrap();",
            "        assert!(fog.syncable);",
            "        assert!(fog.positional);",
            "        assert!(fog.spatially_interpolated);",
            "        assert_eq!(fog.value_type, VanillaEnvironmentAttributeType::RgbColor);",
            "        assert_eq!(",
            "            fog.value_type.modifier_family(),",
            "            VanillaEnvironmentModifierFamily::Rgb",
            "        );",
            "",
            "        let non_positional: Vec<_> = VANILLA_ENVIRONMENT_ATTRIBUTES",
            "            .iter()",
            "            .filter(|entry| !entry.positional)",
            "            .map(|entry| entry.resource_id)",
            "            .collect();",
            "        assert_eq!(",
            "            non_positional,",
            '            ["minecraft:gameplay/sky_light_level", "minecraft:gameplay/fast_lava"]',
            "        );",
            "    }",
            "",
            "    #[test]",
            "    fn environment_attribute_modifier_family_inventory_is_complete() {",
            f"        assert_eq!(VANILLA_ENVIRONMENT_ATTRIBUTE_TYPES.len(), {len(type_entries)});",
            "        let family_counts = VANILLA_ENVIRONMENT_ATTRIBUTE_TYPES.iter().fold(",
            "            [0usize; 6],",
            "            |mut counts, value_type| {",
            "                let index = match value_type.modifier_family() {",
            "                    VanillaEnvironmentModifierFamily::Argb => 0,",
            "                    VanillaEnvironmentModifierFamily::Boolean => 1,",
            "                    VanillaEnvironmentModifierFamily::Float => 2,",
            "                    VanillaEnvironmentModifierFamily::Integer => 3,",
            "                    VanillaEnvironmentModifierFamily::OverrideOnly => 4,",
            "                    VanillaEnvironmentModifierFamily::Rgb => 5,",
            "                };",
            "                counts[index] += 1;",
            "                counts",
            "            },",
            "        );",
            "        assert_eq!(family_counts, [1, 1, 2, 1, 8, 1]);",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generated_catalog(source_root: Path) -> str:
    source_file = source_root / SOURCE_PATH
    source = parse_source(SOURCE_PATH.as_posix(), source_file.read_bytes())
    type_source_file = source_root / TYPE_SOURCE_PATH
    type_source = parse_source(TYPE_SOURCE_PATH.as_posix(), type_source_file.read_bytes())
    rendered = render_catalog(
        environment_attribute_entries(source),
        environment_attribute_type_entries(type_source),
    )
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=rendered,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> int:
    args = parse_args()
    generated = generated_catalog(args.source_root)
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        if current == generated:
            return 0
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile="generated",
            )
        )
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
