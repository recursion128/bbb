#!/usr/bin/env python3
"""Generate Vanilla 26.1 environment-attribute declaration metadata."""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root

from environment_attribute_catalog_extractor import (
    EnvironmentAttributeEntry,
    environment_attribute_entries,
)
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    REPO_ROOT
    / "crates/bbb-world/src/registries/environment_attribute_catalog.rs"
)
SOURCE_PATH = Path("net/minecraft/world/attribute/EnvironmentAttributes.java")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.source_root = resolve_source_root(args)
    return args


def rust_variant(value: str) -> str:
    return "".join(part.title() for part in value.lower().split("_"))


def render_catalog(entries: list[EnvironmentAttributeEntry]) -> str:
    lines = [
        "// @generated by scripts/generate-environment-attribute-catalog.py",
        "// from Vanilla 26.1 EnvironmentAttributes.java. Do not edit by hand.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub(crate) enum VanillaEnvironmentAttributeType {",
    ]
    for value_type in sorted({entry.value_type for entry in entries}):
        lines.append(f"    {rust_variant(value_type)},")
    lines.extend(
        [
            "}",
            "",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub(crate) enum VanillaEnvironmentAttributeRange {",
        ]
    )
    for value_range in sorted({entry.value_range for entry in entries}):
        lines.append(f"    {rust_variant(value_range)},")
    lines.extend(
        [
            "}",
            "",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            "pub(crate) struct VanillaEnvironmentAttribute {",
            "    pub(crate) resource_id: &'static str,",
            "    pub(crate) value_type: VanillaEnvironmentAttributeType,",
            "    pub(crate) value_range: VanillaEnvironmentAttributeRange,",
            "    pub(crate) syncable: bool,",
            "    pub(crate) positional: bool,",
            "    pub(crate) spatially_interpolated: bool,",
            "}",
            "",
            f"pub(crate) const VANILLA_ENVIRONMENT_ATTRIBUTES: [VanillaEnvironmentAttribute; {len(entries)}] = [",
        ]
    )
    for entry in entries:
        lines.extend(
            [
                "    VanillaEnvironmentAttribute {",
                f'        resource_id: "{entry.resource_id}",',
                "        value_type: "
                f"VanillaEnvironmentAttributeType::{rust_variant(entry.value_type)},",
                "        value_range: "
                f"VanillaEnvironmentAttributeRange::{rust_variant(entry.value_range)},",
                f"        syncable: {str(entry.syncable).lower()},",
                f"        positional: {str(entry.positional).lower()},",
                "        spatially_interpolated: "
                f"{str(entry.spatially_interpolated).lower()},",
                "    },",
            ]
        )
    lines.extend(
        [
            "];",
            "",
            "pub(crate) fn vanilla_environment_attribute(",
            "    resource_id: &str,",
            ") -> Option<&'static VanillaEnvironmentAttribute> {",
            "    VANILLA_ENVIRONMENT_ATTRIBUTES",
            "        .iter()",
            "        .find(|entry| entry.resource_id == resource_id)",
            "}",
            "",
            "#[cfg(test)]",
            "mod tests {",
            "    use super::*;",
            "    use std::collections::BTreeSet;",
            "",
            "    #[test]",
            "    fn environment_attribute_catalog_is_complete_ordered_and_unique() {",
            f"        assert_eq!(VANILLA_ENVIRONMENT_ATTRIBUTES.len(), {len(entries)});",
            "        assert_eq!(",
            "            VANILLA_ENVIRONMENT_ATTRIBUTES",
            "                .iter()",
            "                .map(|entry| entry.resource_id)",
            "                .collect::<BTreeSet<_>>()",
            "                .len(),",
            "            VANILLA_ENVIRONMENT_ATTRIBUTES.len()",
            "        );",
            "    }",
            "",
            "    #[test]",
            "    fn environment_attribute_catalog_preserves_builder_flags() {",
            "        let fog = vanilla_environment_attribute(",
            '            "minecraft:visual/fog_color",',
            "        )",
            "        .unwrap();",
            "        assert!(fog.syncable);",
            "        assert!(fog.positional);",
            "        assert!(fog.spatially_interpolated);",
            "        assert_eq!(fog.value_type, VanillaEnvironmentAttributeType::RgbColor);",
            "",
            "        let non_positional: Vec<_> = VANILLA_ENVIRONMENT_ATTRIBUTES",
            "            .iter()",
            "            .filter(|entry| !entry.positional)",
            "            .map(|entry| entry.resource_id)",
            "            .collect();",
            "        assert_eq!(",
            "            non_positional,",
            '            ["minecraft:gameplay/sky_light_level", "minecraft:gameplay/fast_lava"]',
            "        );",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generated_catalog(source_root: Path) -> str:
    source_file = source_root / SOURCE_PATH
    source = parse_source(SOURCE_PATH.as_posix(), source_file.read_bytes())
    rendered = render_catalog(environment_attribute_entries(source))
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=rendered,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> int:
    args = parse_args()
    generated = generated_catalog(args.source_root)
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        if current == generated:
            return 0
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                generated.splitlines(keepends=True),
                fromfile=str(args.output),
                tofile="generated",
            )
        )
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
