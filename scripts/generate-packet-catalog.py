#!/usr/bin/env python3
"""Generate the checked-in vanilla 26.1 packet catalog from Tree-sitter CST facts.

The protocol registration order comes from the five *Protocols.java files. Packet
resource ids come from the corresponding *PacketTypes.java declarations. Normal
builds consume only the generated Rust file; this maintenance tool is the only path
that needs the local decompiled vanilla sources.
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path

from bbb_tools.vanilla.arguments import add_vanilla_root, resolve_source_root

from packet_catalog_extractor import Packet, packet_resource_ids, registered_packets
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO_ROOT / "crates/bbb-protocol/src/packet_catalog.rs"
DEFAULT_COVERAGE_OUTPUT = (
    REPO_ROOT / "docs/evidence/vanilla-26.1/packet-coverage.json"
)
DEFAULT_COVERAGE_OVERRIDES = (
    REPO_ROOT / "scripts/data/packet-coverage-overrides-26.1.json"
)
PROTOCOL_ROOT = Path("net/minecraft/network/protocol")
PROTOCOL_SPECS = (
    ("handshake", "handshake/HandshakeProtocols.java", ("serverbound",)),
    ("status", "status/StatusProtocols.java", ("serverbound", "clientbound")),
    ("login", "login/LoginProtocols.java", ("serverbound", "clientbound")),
    (
        "configuration",
        "configuration/ConfigurationProtocols.java",
        ("serverbound", "clientbound"),
    ),
    ("play", "game/GameProtocols.java", ("serverbound", "clientbound")),
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    add_vanilla_root(parser)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--coverage-output", type=Path, default=DEFAULT_COVERAGE_OUTPUT
    )
    parser.add_argument(
        "--coverage-overrides", type=Path, default=DEFAULT_COVERAGE_OVERRIDES
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.source_root = resolve_source_root(args)
    return args


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_catalog(catalogs: dict[tuple[str, str], list[Packet]]) -> str:
    lines = [
        "// @generated by scripts/generate-packet-catalog.py; do not edit manually.",
        "// Sources: vanilla 26.1 *Protocols.java registration order and *PacketTypes.java ids.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-packet-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-packet-catalog.py --check",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct PacketCatalogEntry {",
        "    pub id: i32,",
        "    pub constant_name: &'static str,",
        "    pub resource_id: &'static str,",
        "    pub class_name: &'static str,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum PacketState {",
        "    Handshake,",
        "    Status,",
        "    Login,",
        "    Configuration,",
        "    Play,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum PacketDirection {",
        "    Serverbound,",
        "    Clientbound,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct PacketCatalog {",
        "    pub state: PacketState,",
        "    pub direction: PacketDirection,",
        "    pub packets: &'static [PacketCatalogEntry],",
        "}",
        "",
    ]
    for state, _, directions in PROTOCOL_SPECS:
        lines.append(f"pub mod {state} {{")
        lines.append("    use super::PacketCatalogEntry;")
        lines.append("")
        for direction in directions:
            packets = catalogs[(state, direction)]
            for packet_id, packet in enumerate(packets):
                lines.append(
                    f"    pub const {packet.constant}: i32 = {packet_id};"
                )
            lines.append("")
            array_name = f"{direction.upper()}_PACKETS"
            lines.append(f"    pub const {array_name}: &[PacketCatalogEntry] = &[")
            for packet_id, packet in enumerate(packets):
                lines.extend(
                    (
                        "        PacketCatalogEntry {",
                        f"            id: {packet_id},",
                        f"            constant_name: {rust_string(packet.constant)},",
                        f"            resource_id: {rust_string(packet.resource_id)},",
                        f"            class_name: {rust_string(packet.class_name)},",
                        "        },",
                    )
                )
            lines.append("    ];")
            lines.append("")
        lines.append("}")
        lines.append("")

    lines.append("pub const VANILLA_PACKET_CATALOGS: &[PacketCatalog] = &[")
    for state, _, directions in PROTOCOL_SPECS:
        state_variant = state.capitalize()
        for direction in directions:
            direction_variant = direction.capitalize()
            lines.extend(
                (
                    "    PacketCatalog {",
                    f"        state: PacketState::{state_variant},",
                    f"        direction: PacketDirection::{direction_variant},",
                    f"        packets: {state}::{direction.upper()}_PACKETS,",
                    "    },",
                )
            )
    lines.append("];\n")
    lines.extend(
        (
            "#[cfg(test)]",
            "mod tests {",
            "    use std::collections::HashSet;",
            "",
            "    use super::*;",
            "",
            "    #[test]",
            "    fn catalogs_are_contiguous_and_unique_per_state_direction() {",
            "        assert_eq!(VANILLA_PACKET_CATALOGS.len(), 9);",
            "        for catalog in VANILLA_PACKET_CATALOGS {",
            "            let mut resource_ids = HashSet::new();",
            "            for (id, packet) in catalog.packets.iter().enumerate() {",
            "                assert_eq!(packet.id, id as i32);",
            "                assert!(resource_ids.insert(packet.resource_id));",
            "                assert!(packet.resource_id.starts_with(\"minecraft:\"));",
            "                assert!(!packet.class_name.is_empty());",
            "            }",
            "        }",
            "    }",
            "",
            "    #[test]",
            "    fn catalog_lengths_and_play_edges_match_vanilla_26_1() {",
            "        assert_eq!(handshake::SERVERBOUND_PACKETS.len(), 1);",
            "        assert_eq!(status::SERVERBOUND_PACKETS.len(), 2);",
            "        assert_eq!(status::CLIENTBOUND_PACKETS.len(), 2);",
            "        assert_eq!(login::SERVERBOUND_PACKETS.len(), 5);",
            "        assert_eq!(login::CLIENTBOUND_PACKETS.len(), 6);",
            "        assert_eq!(configuration::SERVERBOUND_PACKETS.len(), 10);",
            "        assert_eq!(configuration::CLIENTBOUND_PACKETS.len(), 20);",
            "        assert_eq!(play::SERVERBOUND_PACKETS.len(), 69);",
            "        assert_eq!(play::CLIENTBOUND_PACKETS.len(), 141);",
            "        assert_eq!(",
            "            play::CLIENTBOUND_PACKETS.first(),",
            "            Some(&PacketCatalogEntry {",
            "                id: 0,",
            "                constant_name: \"CLIENTBOUND_BUNDLE_DELIMITER\",",
            "                resource_id: \"minecraft:bundle_delimiter\",",
            "                class_name: \"ClientboundBundleDelimiterPacket\",",
            "            })",
            "        );",
            "        assert_eq!(",
            "            play::CLIENTBOUND_PACKETS.last().map(|packet| packet.resource_id),",
            "            Some(\"minecraft:show_dialog\")",
            "        );",
            "    }",
            "",
            "    #[test]",
            "    fn play_clientbound_catalog_and_handwritten_dispatch_cover_each_other() {",
            "        let dispatch = include_str!(\"packets/play_clientbound/dispatch.rs\");",
            "        for packet in play::CLIENTBOUND_PACKETS {",
            "            let needle = format!(\"ids::play::{}\", packet.constant_name);",
            "            assert!(dispatch.contains(&needle), \"missing dispatch arm for {needle}\");",
            "        }",
            "        let dispatch_arm_count = dispatch.match_indices(\"ids::play::CLIENTBOUND_\").count();",
            "        assert_eq!(dispatch_arm_count, play::CLIENTBOUND_PACKETS.len());",
            "    }",
            "}",
            "",
        )
    )
    return "\n".join(lines)


def render_coverage_ledger(
    catalogs: dict[tuple[str, str], list[Packet]],
    overrides: dict[str, dict[str, dict[str, object]]] | None = None,
) -> str:
    protocol_gap = (
        "docs/unsupported-features.md#protocol-coverage-for-remaining-required-261-packet-families"
    )
    clientbound_gap = (
        "docs/unsupported-features.md#unknown-clientbound-packets-in-login-configuration-and-play"
    )

    def coverage(status: str, gap: str) -> dict[str, object]:
        return {"status": status, "evidence": [], "gap": gap}

    overrides = overrides or {}
    used_overrides: set[str] = set()
    allowed_statuses = {
        "complete",
        "partial",
        "deferred",
        "not-applicable",
    }
    entries: list[dict[str, object]] = []
    for state, _, directions in PROTOCOL_SPECS:
        for direction in directions:
            dimensions = (
                {
                    "decode": coverage("partial", protocol_gap),
                    "ownership": coverage("partial", clientbound_gap),
                    "canonical_apply": coverage("partial", clientbound_gap),
                    "runtime_side_effect": coverage("partial", clientbound_gap),
                    "tests": coverage("partial", protocol_gap),
                }
                if direction == "clientbound"
                else {
                    "command_surface": coverage("partial", protocol_gap),
                    "encoder": coverage("partial", protocol_gap),
                    "state_guard": coverage("partial", protocol_gap),
                    "ack_response": coverage("partial", protocol_gap),
                    "tests": coverage("partial", protocol_gap),
                }
            )
            for packet_id, packet in enumerate(catalogs[(state, direction)]):
                packet_key = f"{state}/{direction}/{packet.constant}"
                packet_overrides = overrides.get(packet_key, {})
                if not isinstance(packet_overrides, dict):
                    raise ValueError(f"{packet_key}: override must be an object")
                if packet_key in overrides:
                    used_overrides.add(packet_key)
                unknown_dimensions = set(packet_overrides) - set(dimensions)
                if unknown_dimensions:
                    raise ValueError(
                        f"{packet_key}: unknown coverage dimensions "
                        f"{sorted(unknown_dimensions)}"
                    )
                packet_coverage = {
                    name: dict(cell) for name, cell in dimensions.items()
                }
                for dimension, cell in packet_overrides.items():
                    if not isinstance(cell, dict):
                        raise ValueError(f"{packet_key}/{dimension}: cell must be an object")
                    unknown_cell_keys = set(cell) - {"status", "evidence", "gap"}
                    if unknown_cell_keys:
                        raise ValueError(
                            f"{packet_key}/{dimension}: unknown keys "
                            f"{sorted(unknown_cell_keys)}"
                        )
                    status = cell.get("status")
                    evidence = cell.get("evidence", [])
                    gap = cell.get("gap")
                    if status not in allowed_statuses:
                        raise ValueError(
                            f"{packet_key}/{dimension}: invalid status {status!r}"
                        )
                    if not isinstance(evidence, list) or not all(
                        isinstance(item, str) and item for item in evidence
                    ):
                        raise ValueError(
                            f"{packet_key}/{dimension}: evidence must be non-empty strings"
                        )
                    if status in {"complete", "deferred", "not-applicable"} and not evidence:
                        raise ValueError(
                            f"{packet_key}/{dimension}: {status} cell lacks evidence"
                        )
                    if status != "complete" and not (
                        isinstance(gap, str)
                        and gap.startswith("docs/unsupported-features.md#")
                    ):
                        raise ValueError(
                            f"{packet_key}/{dimension}: non-complete cell lacks gap"
                        )
                    packet_coverage[dimension] = {
                        "status": status,
                        "evidence": evidence,
                        "gap": gap,
                    }
                entries.append(
                    {
                        "state": state,
                        "direction": direction,
                        "id": packet_id,
                        "constant_name": packet.constant,
                        "resource_id": packet.resource_id,
                        "class_name": packet.class_name,
                        "coverage": packet_coverage,
                    }
                )
    unused_overrides = set(overrides) - used_overrides
    if unused_overrides:
        raise ValueError(f"unknown packet coverage overrides: {sorted(unused_overrides)}")
    value = {
        "schema_version": 1,
        "vanilla_version": "26.1",
        "generated_by": "scripts/generate-packet-catalog.py",
        "update_command": (
            "scripts/vanilla-source-tools.sh scripts/generate-packet-catalog.py"
        ),
        "check_command": (
            "scripts/vanilla-source-tools.sh scripts/generate-packet-catalog.py --check"
        ),
        "coverage_overrides": "scripts/data/packet-coverage-overrides-26.1.json",
        "allowed_statuses": sorted(allowed_statuses),
        "baseline_policy": (
            "Inventory foundation: every cell remains partial until its packet family "
            "is audited against vanilla source and carries implementation/test evidence."
        ),
        "entries": entries,
    }
    return json.dumps(value, indent=2, sort_keys=True) + "\n"


def extract_catalogs(source_root: Path) -> dict[tuple[str, str], list[Packet]]:
    protocol_root = source_root / PROTOCOL_ROOT
    packet_type_sources = [
        parse_source(path.relative_to(source_root).as_posix(), path.read_bytes())
        for path in sorted(protocol_root.rglob("*PacketTypes.java"))
    ]
    resources = packet_resource_ids(packet_type_sources)
    catalogs: dict[tuple[str, str], list[Packet]] = {}
    for state, relative_path, directions in PROTOCOL_SPECS:
        path = protocol_root / relative_path
        source = parse_source(path.relative_to(source_root).as_posix(), path.read_bytes())
        for direction in directions:
            catalogs[(state, direction)] = registered_packets(
                source, direction, resources
            )
    return catalogs


def load_coverage_overrides(path: Path) -> dict[str, dict[str, dict[str, object]]]:
    def strict_object(pairs):
        value = {}
        for key, item in pairs:
            if key in value:
                raise ValueError(f"{path}: duplicate JSON key {key!r}")
            value[key] = item
        return value

    value = json.loads(path.read_text(), object_pairs_hook=strict_object)
    if value.get("schema_version") != 1 or not isinstance(value.get("entries"), dict):
        raise ValueError(f"{path}: invalid packet coverage override schema")
    return value["entries"]


def validate_coverage_evidence(
    overrides: dict[str, dict[str, dict[str, object]]], source_root: Path
) -> None:
    for packet_key, dimensions in overrides.items():
        for dimension, cell in dimensions.items():
            for evidence in cell.get("evidence", []):
                if "#" not in evidence:
                    raise ValueError(
                        f"{packet_key}/{dimension}: malformed evidence {evidence!r}"
                    )
                locator, symbol = evidence.split("#", 1)
                if not symbol:
                    raise ValueError(
                        f"{packet_key}/{dimension}: evidence lacks symbol {evidence!r}"
                    )
                if locator.startswith("vanilla:"):
                    relative_path = locator.removeprefix("vanilla:")
                    root = source_root
                else:
                    relative_path = locator
                    root = REPO_ROOT
                path = Path(relative_path)
                if path.is_absolute() or ".." in path.parts:
                    raise ValueError(
                        f"{packet_key}/{dimension}: evidence path must be relative {evidence!r}"
                    )
                source_path = root / path
                if not source_path.is_file():
                    raise ValueError(
                        f"{packet_key}/{dimension}: evidence file does not exist: {evidence}"
                    )
                if symbol not in source_path.read_text():
                    raise ValueError(
                        f"{packet_key}/{dimension}: evidence symbol not found: {evidence}"
                    )


def generate(source_root: Path, overrides_path: Path) -> tuple[str, str]:
    catalogs = extract_catalogs(source_root)
    overrides = load_coverage_overrides(overrides_path)
    validate_coverage_evidence(overrides, source_root)
    rendered = render_catalog(catalogs)
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=rendered,
        text=True,
        capture_output=True,
        check=True,
    )
    return formatted.stdout, render_coverage_ledger(catalogs, overrides)


def check_output(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    catalog, coverage = generate(args.source_root, args.coverage_overrides)
    if args.check:
        catalog_matches = check_output(args.output, catalog)
        coverage_matches = check_output(args.coverage_output, coverage)
        return 0 if catalog_matches and coverage_matches else 1
    args.output.write_text(catalog)
    args.coverage_output.write_text(coverage)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
