#!/usr/bin/env python3
"""Generate the checked-in vanilla 26.1 jukebox-song descriptor catalog."""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

from jukebox_song_catalog_extractor import jukebox_song_entries
from vanilla_java_source import parse_source


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_ROOT = Path.home() / "Work/mc-code/sources/26.1"
DEFAULT_OUTPUT = (
    REPO_ROOT / "crates/bbb-pack/src/jukebox_song_registry/generated_26_1.rs"
)
JUKEBOX_SONGS_SOURCE = Path("net/minecraft/world/item/JukeboxSongs.java")
SOUND_EVENTS_SOURCE = Path("net/minecraft/sounds/SoundEvents.java")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, default=DEFAULT_SOURCE_ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def parse_java(source_root: Path, relative_path: Path):
    return parse_source(relative_path.as_posix(), (source_root / relative_path).read_bytes())


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(source_root: Path) -> str:
    entries = jukebox_song_entries(
        parse_java(source_root, JUKEBOX_SONGS_SOURCE),
        parse_java(source_root, SOUND_EVENTS_SOURCE),
    )
    lines = [
        "// @generated by scripts/generate-jukebox-song-catalog.py; do not edit manually.",
        "// Source: vanilla 26.1 JukeboxSongs bootstrap and SoundEvents registrations.",
        "// Update: scripts/vanilla-source-tools.sh scripts/generate-jukebox-song-catalog.py",
        "// Check: scripts/vanilla-source-tools.sh scripts/generate-jukebox-song-catalog.py --check",
        "",
        "use super::VanillaJukeboxSong;",
        "",
        "pub(super) const VANILLA_26_1_JUKEBOX_SONGS: &[VanillaJukeboxSong] = &[",
    ]
    for entry in entries:
        lines.extend(
            (
                "    VanillaJukeboxSong {",
                f"        song_id: {rust_string(entry.resource_id)},",
                f"        sound_event_id: {rust_string(entry.sound_event_id)},",
                "    },",
            )
        )
    lines.extend(("];", ""))
    return "\n".join(lines)


def check_generated(path: Path, generated: str) -> bool:
    current = path.read_text() if path.exists() else ""
    if current == generated:
        return True
    sys.stderr.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=str(path),
            tofile="generated",
        )
    )
    return False


def main() -> int:
    args = parse_args()
    generated = generate(args.source_root)
    if args.check:
        return 0 if check_generated(args.output, generated) else 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
