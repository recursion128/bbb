/// Renderer-owned frame/draw counters.
///
/// This is the renderer's source-of-truth counter block, updated as frames are
/// rendered, terrain is uploaded, atlases reallocate, and particles tick. The
/// downstream control crate keeps its own snapshot-facing `RendererCounters`
/// mirror; the native runtime projects this struct's fields into that mirror at
/// the snapshot boundary (mirroring the `NetCounters` pattern). Keeping the
/// authoritative counters here lets `bbb-control` stay a purely derived view
/// without depending on the renderer (and pulling in wgpu).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct TerrainMeshWorkerCounters {
    pub queued_jobs: u64,
    pub completed_jobs: u64,
    pub stale_jobs: u64,
    pub queued_sections: u64,
    pub completed_sections: u64,
    pub stale_sections: u64,
    pub queue_full: u64,
    pub queue_depth: usize,
    pub peak_queue_depth: usize,
    pub recent_build_nanos: u64,
    pub peak_build_nanos: u64,
    pub recent_build_sections: usize,
    pub peak_build_sections: usize,
}

