/// Projects one of the codec-retained persistent values with the same parser
/// and canonicalizer the network decoder owns. `false` means either a lossy
/// component or a value that cannot inhabit that retained wire shape.
pub(super) fn project_retained_persistent_component(
    type_id: i32,
    value: &NbtSummaryValue,
    patch: &mut DataComponentPatchSummary,
) -> bool {
    match type_id {
        VANILLA_DATA_COMPONENT_CUSTOM_DATA_TYPE_ID => {
            let Some(value) = custom_data_compound(value) else {
                return false;
            };
            patch.custom_data = Some(value.into_owned());
        }
        VANILLA_DATA_COMPONENT_MAP_DECORATIONS_TYPE_ID => {
            let Ok(decorations) = parse_map_decorations_nbt(value) else {
                return false;
            };
            let canonical = canonical_map_decorations_nbt(&decorations);
            patch.map_decorations = Some(decorations);
            patch.codec_backed_nbt.insert(type_id, canonical);
        }
        VANILLA_DATA_COMPONENT_BUCKET_ENTITY_DATA_TYPE_ID => {
            let Some(value) = custom_data_compound(value) else {
                return false;
            };
            patch.codec_backed_nbt.insert(type_id, value.into_owned());
        }
        VANILLA_DATA_COMPONENT_RECIPES_TYPE_ID => {
            let Ok(recipes) = parse_recipe_keys_nbt(value) else {
                return false;
            };
            let canonical = canonical_recipe_keys_nbt(&recipes);
            patch.recipe_keys = Some(recipes);
            patch.codec_backed_nbt.insert(type_id, canonical);
        }
        VANILLA_DATA_COMPONENT_CONTAINER_LOOT_TYPE_ID => {
            let Ok((loot_table, seed)) = parse_container_loot_nbt(value) else {
                return false;
            };
            let canonical = canonical_container_loot_nbt(&loot_table, seed);
            patch.container_loot = true;
            patch.container_loot_table = Some(loot_table);
            patch.container_loot_seed = Some(seed);
            patch.codec_backed_nbt.insert(type_id, canonical);
        }
        _ => return false,
    }
    true
}

/// `CustomData.COMPOUND_TAG_CODEC` accepts a compound
/// or flattened SNBT, including the typed entity data reader's tag.
pub(super) fn custom_data_compound(value: &NbtSummaryValue) -> Option<Cow<'_, NbtSummaryValue>> {
    if matches!(value, NbtSummaryValue::Compound(_)) {
        return Some(Cow::Borrowed(value));
    }
    let source = bbb_protocol::JavaString::from_nbt(value)?;
    bbb_protocol::parse_snbt_compound_utf16(source.units())
        .ok()
        .map(Cow::Owned)
}

/// The persistent codec NBT the wire decode kept for one component, or `None`
/// when the summary only holds a lossy typed projection of it.
pub(super) fn retained_persistent_component_nbt(
    type_id: i32,
    patch: &DataComponentPatchSummary,
) -> Option<&NbtSummaryValue> {
    // `minecraft:custom_data` is `persistent(CustomData.CODEC)` with no
    // `networkSynchronized`, and `CustomData` is a
    // bare `CompoundTag` on both sides, so the
    // decoded compound is already the save value.
    if type_id == VANILLA_DATA_COMPONENT_CUSTOM_DATA_TYPE_ID {
        return patch.custom_data.as_ref();
    }
    if !PERSISTENT_CODEC_BACKED_COMPONENT_TYPE_IDS.contains(&type_id) {
        return None;
    }
    patch.codec_backed_nbt.get(&type_id)
}

/// Resolves one declared patch entry, rejecting a type id the patch already
/// used. A Vanilla patch is a map keyed by `DataComponentType`, so no id can
/// appear twice, on either side (`DataComponentPatch.java:41-53`).
pub(super) fn declared_component(
    type_id: i32,
    seen: &mut BTreeSet<i32>,
) -> Result<&'static DataComponentTypeCatalogEntry> {
    if !seen.insert(type_id) {
        return Err(ItemStackPersistentProjectionError::DuplicateComponent { type_id });
    }
    vanilla_data_component_type(type_id)
        .ok_or(ItemStackPersistentProjectionError::UnknownComponent { type_id })
}
