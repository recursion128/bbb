pub(super) fn write_component_condition_entry(
    assets: &Path,
    item_id: &str,
    predicate: &str,
    value_json: Option<&str>,
) {
    let prefix = if item_id == "enchanted_book" {
        "component_condition_stored_enchantments_default"
    } else {
        item_id
    };
    let mut model = serde_json::Map::new();
    model.insert("type".into(), serde_json::json!("minecraft:condition"));
    model.insert("property".into(), serde_json::json!("minecraft:component"));
    model.insert("predicate".into(), serde_json::json!(predicate));
    if let Some(raw_value) = value_json {
        model.insert("value".into(), serde_json::from_str(raw_value).unwrap());
    }
    model.insert(
        "on_true".into(),
        serde_json::json!({ "type": "minecraft:model", "model": format!("minecraft:item/{prefix}_present") }),
    );
    model.insert(
        "on_false".into(),
        serde_json::json!({ "type": "minecraft:model", "model": format!("minecraft:item/{prefix}_absent") }),
    );
    write_json(
        &assets.join("items").join(format!("{item_id}.json")),
        &serde_json::json!({ "model": model }).to_string(),
    );
}

