use std::env;
use std::fs;
use std::io::Write;
use std::path::PathBuf;
use std::process::{Command, Stdio};

use anyhow::{bail, Context, Result};
use bbb_pack::ItemRegistryCatalog;

fn main() -> Result<()> {
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .context("bbb-pack manifest must be under the repository root")?
        .to_path_buf();
    let mut source_root = env::var_os("HOME")
        .map(PathBuf::from)
        .context("HOME is required when --source-root is omitted")?
        .join("Work/mc-code/sources/26.1");
    let mut output = repo_root.join("crates/bbb-protocol/src/item_types.rs");
    let mut check = false;

    let mut args = env::args_os().skip(1);
    while let Some(arg) = args.next() {
        match arg.to_str() {
            Some("--source-root") => {
                source_root = PathBuf::from(
                    args.next()
                        .context("--source-root requires a path argument")?,
                );
            }
            Some("--output") => {
                output = PathBuf::from(args.next().context("--output requires a path argument")?);
            }
            Some("--check") => check = true,
            _ => bail!("unknown argument {}", arg.to_string_lossy()),
        }
    }

    let catalog = ItemRegistryCatalog::load_from_java_sources(
        source_root.join("net/minecraft/world/item/Items.java"),
        source_root.join("net/minecraft/references/ItemIds.java"),
    )
    .context("load vanilla item registry")?;
    let generated = format_rust(&render_item_catalog(&catalog))?;

    if check {
        let current = fs::read_to_string(&output).unwrap_or_default();
        if current != generated {
            bail!("{} is out of date", output.display());
        }
    } else {
        fs::write(&output, generated)
            .with_context(|| format!("write generated item catalog to {}", output.display()))?;
    }
    Ok(())
}

fn render_item_catalog(catalog: &ItemRegistryCatalog) -> String {
    assert_eq!(catalog.len(), 1506, "vanilla 26.1 item count changed");
    let mut lines = vec![
        "// @generated by crates/bbb-pack/examples/generate_item_registry_catalog.rs; do not edit manually.".to_string(),
        "// Source: vanilla 26.1 Items.java registration order via bbb-pack::ItemRegistryCatalog.".to_string(),
        String::new(),
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]".to_string(),
        "pub struct ItemTypeCatalogEntry {".to_string(),
        "    pub id: i32,".to_string(),
        "    pub resource_id: &'static str,".to_string(),
        "}".to_string(),
        String::new(),
    ];

    for (id, resource_id) in catalog.resource_ids().iter().enumerate() {
        lines.push(format!(
            "pub const VANILLA_ITEM_{}_ID: i32 = {id};",
            item_constant_name(resource_id)
        ));
    }
    lines.push(String::new());
    lines.push("pub const VANILLA_ITEM_TYPES: &[ItemTypeCatalogEntry] = &[".to_string());
    for (id, resource_id) in catalog.resource_ids().iter().enumerate() {
        lines.extend([
            "    ItemTypeCatalogEntry {".to_string(),
            format!("        id: {id},"),
            format!("        resource_id: {resource_id:?},"),
            "    },".to_string(),
        ]);
    }
    lines.extend([
        "];".to_string(),
        String::new(),
        "pub fn vanilla_item_type(id: i32) -> Option<&'static ItemTypeCatalogEntry> {".to_string(),
        "    VANILLA_ITEM_TYPES.get(usize::try_from(id).ok()?)".to_string(),
        "}".to_string(),
        String::new(),
        "pub fn vanilla_item_type_for_resource_id(".to_string(),
        "    resource_id: &str,".to_string(),
        ") -> Option<&'static ItemTypeCatalogEntry> {".to_string(),
        "    let resource_id = resource_id".to_string(),
        "        .strip_prefix(\"minecraft:\")".to_string(),
        "        .unwrap_or(resource_id);".to_string(),
        "    VANILLA_ITEM_TYPES".to_string(),
        "        .iter()".to_string(),
        "        .find(|entry| entry.resource_id.strip_prefix(\"minecraft:\") == Some(resource_id))"
            .to_string(),
        "}".to_string(),
        String::new(),
        "#[cfg(test)]".to_string(),
        "mod tests {".to_string(),
        "    use std::collections::HashSet;".to_string(),
        String::new(),
        "    use super::*;".to_string(),
        String::new(),
        "    #[test]".to_string(),
        "    fn item_catalog_is_complete_contiguous_and_unique() {".to_string(),
        "        assert_eq!(VANILLA_ITEM_TYPES.len(), 1506);".to_string(),
        "        let mut resources = HashSet::new();".to_string(),
        "        for (id, entry) in VANILLA_ITEM_TYPES.iter().enumerate() {".to_string(),
        "            assert_eq!(entry.id, id as i32);".to_string(),
        "            assert!(entry.resource_id.starts_with(\"minecraft:\"));".to_string(),
        "            assert!(resources.insert(entry.resource_id));".to_string(),
        "        }".to_string(),
        "    }".to_string(),
        String::new(),
        "    #[test]".to_string(),
        "    fn item_catalog_preserves_vanilla_registration_order() {".to_string(),
        "        assert_eq!(VANILLA_ITEM_AIR_ID, 0);".to_string(),
        "        assert_eq!(VANILLA_ITEM_SADDLE_ID, 838);".to_string(),
        "        assert_eq!(VANILLA_ITEM_ELYTRA_ID, 863);".to_string(),
        "        assert_eq!(VANILLA_ITEM_SNOWBALL_ID, 1017);".to_string(),
        "        assert_eq!(VANILLA_ITEM_EGG_ID, 1032);".to_string(),
        "        assert_eq!(VANILLA_ITEM_ENDER_EYE_ID, 1129);".to_string(),
        "        assert_eq!(VANILLA_ITEM_SPLASH_POTION_ID, 1292);".to_string(),
        "        assert_eq!(VANILLA_ITEM_OMINOUS_BOTTLE_ID, 1505);".to_string(),
        "        assert_eq!(vanilla_item_type(-1), None);".to_string(),
        "        assert_eq!(vanilla_item_type(1506), None);".to_string(),
        "        assert_eq!(".to_string(),
        "            vanilla_item_type_for_resource_id(\"snowball\").unwrap().id,".to_string(),
        "            VANILLA_ITEM_SNOWBALL_ID".to_string(),
        "        );".to_string(),
        "        assert_eq!(".to_string(),
        "            vanilla_item_type_for_resource_id(\"example:snowball\"),".to_string(),
        "            None".to_string(),
        "        );".to_string(),
        "    }".to_string(),
        "}".to_string(),
        String::new(),
    ]);
    lines.join("\n")
}

fn item_constant_name(resource_id: &str) -> String {
    let path = resource_id
        .strip_prefix("minecraft:")
        .expect("vanilla item resource id must use the minecraft namespace");
    assert!(
        path.bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_'),
        "item resource path is not a Rust constant suffix: {path}"
    );
    path.to_ascii_uppercase()
}

fn format_rust(rendered: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .context("spawn rustfmt")?;
    child
        .stdin
        .as_mut()
        .context("open rustfmt stdin")?
        .write_all(rendered.as_bytes())
        .context("write rustfmt input")?;
    let output = child.wait_with_output().context("wait for rustfmt")?;
    if !output.status.success() {
        bail!("rustfmt failed with {}", output.status);
    }
    String::from_utf8(output.stdout).context("rustfmt output is not UTF-8")
}
